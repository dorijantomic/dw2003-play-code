import { flagConditionPasses } from './story-command-banks.ts';
// The field scene system's per-place GATE OBJECTS — the shared routine every place's
// own object runs to decide which scene this place starts, ported once.
//
// The original is 78 per-place copies of the same routine, each with its own candidate
// chain as DATA: 76 overlays install one on the stage's ENTRY object and s795/s800
// install a second alongside it. What the copies share is the whole decision
// procedure; what each place supplies is the chain and its phase band. So this
// module is the procedure and nothing else:
//
//   * the gate object reads its own phase word at +0xc and runs the chain only on
//     its own band — the reset band (0, negative, >= 4; pro/wstag200.s:24-34,
//     pro/wstag305.s:196-203) on the entry object, phase 1 on the second one
//     (pro/wstag795.s:0x5b4-0x5d0). Every exit path advances the phase through the
//     object's own `vt+0x38`, which is what makes the decision once per field load.
//   * each candidate is an ordered conjunction of one ordinal equality and any
//     number of get_flag expectations. `0x6000|n` is the master story ordinal
//     [0x8004B370]; every other id is a flag predicate read through get_flag
//     (0x80048ACC), which returns nonzero iff flag == expected.
//   * the chain is walked in order and the FIRST candidate whose whole
//     conjunction holds wins. Every ordinal re-read in the original re-tests the
//     same single linear value, so it never opens a second dimension.
//   * AT MOST ONE event is started per pass. When no candidate holds, the
//     original starts nothing and falls through to the object's own +0x38
//     method (pro/wstag440.s:52-60: the `bne` targets a label PAST the jal).
//   * a chain that also tests the scene descriptor idle (0x80099D80+0x50/54/58/5c/60
//     — the runner/step latches) starts nothing while another scene holds the field;
//     that is what "at most one runner" means, and the engine's own start path
//     already refuses a second one.
//
// The chain data lives in web/assets/data/scene/arrival_candidates.json,
// generated by tools/extract_arrival_candidates.py, and is loaded through
// setArrivalChains(). The predicate is a callback, not a table: which flag ids
// the engine can actually evaluate is the flag system's business (see
// DW3_BANK_SCHEME / dw3-config.ts), and a caller that cannot evaluate one says
// so the same way the converter's gate compiler does — by not asking.

/** A conjunction as the original's branch chain builds it. Ordinal leaves are
 *  encoded as `0x6000 | n`; flag leaves are the raw predicate id. */
export type ArrivalLeaf = readonly [number, number];

/** One candidate of the chain: the event id, and every path that reaches it.
 *  More than one path means the original can reach the same event through two
 *  different routes (s305 893 arrives both with and without the 0x4057 test
 *  passed); the candidate is reached when ANY path's conjunction holds. */
export interface ArrivalCandidate {
  /** The id the original passes to start_event (0x800853f8). */
  event: number;
  /** Conjunctions, one per route from the chain's entry to this candidate. */
  paths: readonly (readonly ArrivalLeaf[])[];
  /** pro/wstagNNN.s line + label of the `jal start_event` — the citation. */
  cite?: string;
}

/** One place's gate object: its own chain, in order. */
export interface ArrivalChain {
  mapId: string;
  /** The overlay word the gate-object constructor hands F0x80014504. */
  tick: string;
  candidates: readonly ArrivalCandidate[];
  /** Which phase band the object tests its chain on. See ARRIVAL_BANDS. */
  band?: ArrivalBand;
}

/** The two phase bands the disc's per-place gate objects ship.
 *
 *  `reset`  — the chain runs while the phase word is 0, negative or >= 4 (the 76
 *             overlays that own the stage's ENTRY object: pro/wstag200.s:24-34,
 *             pro/wstag305.s:196-203). A fresh object reads 0, so the chain is
 *             asked on the object's FIRST turn; every exit path advances the phase
 *             through the object's own `vt+0x38` (exe/fns.s:8955-8963
 *             F0x800142ac, `phase = phase + 1`), which is the one-shot latch.
 *  `phase1` — the chain runs while the phase word is exactly 1 (s795's and s800's
 *             SECOND gate object: pro/wstag795.s:0x5b4-0x5d0, pro/wstag800.s:0x8c0-0x8dc).
 *             A fresh object reads 0 and its phase-0 arm returns through the same
 *             `vt+0x38`, so this object reaches its band on its SECOND turn and
 *             latches the same way. Two overlays ship this shape.
 *
 * The walker raises a stage's gate objects once per field load, which is the same
 * instant the disc reaches both objects' decision turns: a fresh allocation is
 * phase 0, and the advance to the decision band happens before the field is
 * playable. So a chain is evaluated on the field-load raise whichever band it uses.
 */
export type ArrivalBand = "reset" | "phase1";

/** Predicate test: does flag `id` currently read as `expected`? */
export type ArrivalTest = (id: number, expected: number) => boolean;

/** Does this gate object's own phase word put it ON its chain band? */
export function arrivalRunsOnPhase(phase: number, band: ArrivalBand = "reset"): boolean {
  if (band === "phase1") return phase === 1;
  return phase === 0 || phase < 0 || phase >= 4;
}

function holds(leaves: readonly ArrivalLeaf[], test: ArrivalTest): boolean {
  for (const [id, expected] of leaves) if (!test(id, expected)) return false;
  return true;
}

/** The event id this place starts on arrival, or null when it starts nothing.
 *  First whole match wins; at most one event per pass. */
export function chooseArrivalEvent(
  chain: ArrivalChain | null | undefined,
  test: ArrivalTest,
): number | null {
  if (!chain) return null;
  for (const c of chain.candidates) {
    for (const p of c.paths) {
      if (holds(p, test)) return c.event;
    }
  }
  return null;
}

/** The same decision, with the phase word supplied: the engine calls this on stage
 *  arrival with the gate object's phase (0 for a fresh entry). */
export function arrivalEventForPhase(
  chain: ArrivalChain | null | undefined,
  phase: number,
  test: ArrivalTest,
): number | null {
  return arrivalRunsOnPhase(phase, chain?.band) ? chooseArrivalEvent(chain, test) : null;
}

/** The candidates that come BEFORE `event` in the chain. Used by the converter to
 *  keep two candidates of one beat from both matching: the original's chain order
 *  means an earlier candidate wins, so an event row must exclude the earlier ones.
 *  Empty when the event is not in the chain, or when nothing precedes it. */
export function earlierCandidates(
  chain: ArrivalChain | null | undefined,
  event: number,
): ArrivalCandidate[] {
  if (!chain) return [];
  const out: ArrivalCandidate[] = [];
  for (const c of chain.candidates) {
    if (c.event === event) return out;
    out.push(c);
  }
  return out;
}

/** Build a test from a plain flag reader, so a caller with a live flag store
 *  does not have to write the closure itself. */
export function flagTest(get: (id: number) => number): ArrivalTest {
  return (id, expected) => flagConditionPasses(get, id, expected);
}

const CHAINS = new Map<string, ArrivalChain[]>();

/** Install the extracted chains. `raw` is the parsed arrival_candidates.json
 *  (`{ stages: { s305: { candidates: [...] } } }`). A stage holds a LIST when its
 *  overlay installs more than one phase-gated gate object: 76 overlays install one
 *  (the stage's ENTRY object, reset band) and s795/s800 install a SECOND whose band
 *  is `phase1`. Every one is installed; `arrivalChain(mapId)` returns the stage's
 *  entry object and `arrivalGateObjects(mapId)` returns them all. */
type RawGateRow = ArrivalChain & { phase_gate?: { band?: string } };
export function setArrivalChains(raw: {
  stages?: Record<string, RawGateRow | RawGateRow[]>;
}): void {
  CHAINS.clear();
  for (const [mapId, v] of Object.entries(raw.stages ?? {})) {
    const rows = (Array.isArray(v) ? v : [v]).filter(Boolean);
    if (rows.length) {
      CHAINS.set(mapId, rows.map(r => ({
        ...r,
        mapId,
        band: (r.band ?? r.phase_gate?.band ?? "reset") as ArrivalBand,
      })));
    }
  }
}

/** The stage's ENTRY gate object (the reset-band one), or null. */
export function arrivalChain(mapId: string): ArrivalChain | null {
  const rows = CHAINS.get(mapId);
  if (!rows?.length) return null;
  return rows.find(r => (r.band ?? "reset") === "reset") ?? rows[0]!;
}

/** EVERY gate object this place installs, in the order the overlay allocates them. */
export function arrivalGateObjects(mapId: string): readonly ArrivalChain[] {
  return CHAINS.get(mapId) ?? [];
}

/** Every installed gate object, for tests and for the converter's audit. */
export function arrivalChains(): ArrivalChain[] {
  return [...CHAINS.values()].flat();
}