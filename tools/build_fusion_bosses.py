#!/usr/bin/env python3
"""Build web/fusion_bosses.json from data/authored/fusion_bosses.json + data/authored/fusion_skills.json.

    python3 tools/build_fusion_bosses.py            writes web/fusion_bosses.json
    python3 tools/build_fusion_bosses.py --check    builds in memory and fails if web/fusion_bosses.json is out of date

The authored files hold intent only: the two halves, the body, the display name, a level, the
screens whose HP add up, the screen whose stat scale is borrowed, the three move ids and a
tint. This script checks every name and id against the game's own tables and writes the
resolved records:

  * the fused HP is the two encounter screens' party HP added (1176 + 1248 = 2424);
  * the fused stat scale is the boss screen's own stat_scale + the authored delta (16 + 2 = 18).

Those are the only two numbers read from the encounter table; no enemy row is copied into the
output. A half that is not a real species is refused, as is a move id that is not a real
technique. A technique in fusion_skills.json is built on a real technique row (base): the
fields it does not author are copied from that row, and its effect is checked against the
real row the effect is taken from (effect_from), including that the applier byte really is
the ailment it names.

Do not edit web/fusion_bosses.json by hand.
"""
import json
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
DATA = os.path.join(ROOT, "web", "assets", "data")
SRC = os.path.join(ROOT, "data", "authored")
OUT = os.path.join(ROOT, "web", "fusion_bosses.json")

COMMENT = ("Fusion bosses (new content, not part of the shipped game). GENERATED by "
           "tools/build_fusion_bosses.py from data/authored/fusion_bosses.json and "
           "data/authored/fusion_skills.json - edit the sources, not this file. Every species, "
           "screen and move named here is checked against the game's own tables; the only "
           "numbers read from the encounter table are the two screen HP that add up to the "
           "fused HP and the boss screen's stat scale.")

# The technique record's +0x0A dispatch byte (f7) -> the ailment applier it selects. The
# table is the original's own dispatch (0x80083234 routes f7 2/3/4/5/6/8 to the appliers
# d140/d1dc/d2c4/d3ac/d470/d61c: poison / paralyze / confuse / sleep / instant-death / drain,
# docs/research/battle/battle-formula-leaves.md:776-778).
APPLIERS = {
    2: "poison", 3: "paralyze", 4: "confuse", 5: "sleep",
    6: "instant_death", 8: "drain", 9: "multihit", 10: "counter",
    11: "precision", 12: "steal",
}
AUTHORED_SKILL_MIN = 9000      # authored technique ids live above the real table's 443 rows
TRANSFORMS = {"whiteout"}
# Boss phases (web/boss-phase.js): the seven elemental fields a phase may set. Ids 2..8
# are the disc's own ELEMENT_ID (engine/dw3/battle-formulas.ts); `normal` (1) is not a
# battlefield, so it is not a phase field.
PHASE_FIELDS = {"fire", "water", "ice", "wind", "thunder", "machine", "dark"}
MAX_PHASES = 3


class BuildError(Exception):
    pass


def load(name):
    path = os.path.join(DATA, name)
    try:
        return json.load(open(path, encoding="utf-8"))
    except FileNotFoundError:
        raise BuildError(f"missing {os.path.relpath(path, ROOT)} (the decoded game tables must be present)")


def is_int(value):
    return isinstance(value, int) and not isinstance(value, bool)


def battle_banks():
    """Every battle bank the game's own battle-music table names — never a hardcoded list.

    web/assets/data/battle_music.json is the decoded trigger table (128 screen keys, 310
    records). Each record's `bank` is the track the field handoff copies into the packed
    battle-music word (archive = (id >> 18) & 0x7f, played by wfightmn); a phase may name
    one of those and nothing else.
    """
    banks = set()
    for records in load("battle_music.json").values():
        for row in records:
            bank = row.get("bank")
            if isinstance(bank, str) and bank:
                banks.add(bank)
    return banks


def resolve_skill(row, real_skills, fight_tech):
    sid = row.get("id")
    if not is_int(sid) or sid < AUTHORED_SKILL_MIN:
        raise BuildError(f"authored skill id {sid!r} must be an integer >= {AUTHORED_SKILL_MIN}")
    if sid in real_skills:
        raise BuildError(f"authored skill {sid} collides with a real technique row")
    base_id = row.get("base")
    base = real_skills.get(base_id)
    if not base:
        raise BuildError(f"skill {sid}: base {base_id!r} is not a real technique (not in digimon.json)")
    name = row.get("name")
    if not isinstance(name, str) or not name.strip():
        raise BuildError(f"skill {sid}: needs a name")
    power = row.get("power")
    if not is_int(power) or not 1 <= power <= 999:
        raise BuildError(f"skill {sid}: power {power!r} must be an integer 1..999")
    # Everything the row does not author comes from the real base row, and what it does
    # author must agree with it: a new move may be stronger or renamed, never a different
    # kind of move.
    for field, key, want in (
        ("mp", "mp_cost", row.get("mp")),
        ("element", "element", row.get("element")),
        ("category", "attack_category", row.get("category")),
        ("clip", "clip", row.get("clip")),
    ):
        if want is not None and want != base.get(key):
            raise BuildError(f"skill {sid}: {field} {want!r} disagrees with base {base_id}'s {key} {base.get(key)!r}")
    effect_id = row.get("effect_id")
    if effect_id not in APPLIERS:
        raise BuildError(f"skill {sid}: effect_id {effect_id!r} is not a real technique applier byte")
    effect_from = row.get("effect_from")
    source = real_skills.get(effect_from)
    tech = fight_tech.get(str(effect_from)) if effect_from is not None else None
    if not source or not tech:
        raise BuildError(f"skill {sid}: effect_from {effect_from!r} is not a real technique row")
    if tech.get("dispatch") != effect_id:
        raise BuildError(f"skill {sid}: effect_from {effect_from} dispatches {tech.get('dispatch')!r}, not {effect_id}")
    if source.get("effect") != APPLIERS[effect_id]:
        raise BuildError(f"skill {sid}: applier {effect_id} is {APPLIERS[effect_id]!r} but row {effect_from} carries "
                         f"effect {source.get('effect')!r}")
    effect_power = row.get("effect_power")
    if effect_power != tech.get("crit"):
        raise BuildError(f"skill {sid}: effect_power {effect_power!r} is not row {effect_from}'s own +0x0C power "
                         f"{tech.get('crit')!r}")
    resolved = {
        "id": sid,
        "name": name.strip(),
        "desc": str(row.get("desc") or ""),
        "mp_cost": base.get("mp_cost"),
        "power": power,
        "element": base.get("element"),
        "attack_category": base.get("attack_category"),
        "attack_cat": base.get("attack_cat"),
        "type": base.get("type"),
        "target_family": base.get("target_family"),
        "damage_scalar": base.get("damage_scalar"),
        "hits": base.get("hits"),
        "clip": base.get("clip"),
        "effect": source.get("effect"),
        "effect_p1": source.get("effect_p1"),
        "effect_p2": source.get("effect_p2"),
        "effect_id": effect_id,
        "effect_power": effect_power,
        "base": base_id,
    }
    return str(sid), resolved


def resolve_phases(bid, phases, moves):
    """The authored HP phases of one boss, validated and resolved.

    A phase is `{at, moves, page}` plus optional `field`, `tint` and `music`;
    `web/boss-phase.js` reads exactly those. The rules keep the battle's phase machine
    simple and honest:

      * at most three phases, and `at` strictly descending (0.6 then 0.25) so the page
        of a phase a single hit skips never stacks on top of the newest one;
      * `at` is a number 0.05..0.95 — a phase can never fire on the first or last blow;
      * 1..3 `moves`, each one of the boss's OWN moves (the three technique ids the boss
        record already names; actions 1..3, never flee or a slot switch);
      * `field` is one of the disc's seven elemental fields (2..8, never `normal`);
      * `tint` is four numbers 0..1, the same shape the boss's own tint has;
      * `page` is the authored line the phase puts up (non-empty);
      * `music` is one of the banks the game's own battle_music.json names (computed by
        `battle_banks()`), so the fight's track can turn at the phase's HP line;
      * `size` is a body multiplier 0.5..8 with at most one decimal, never smaller than
        an earlier phase's size (a boss only grows), so a phase can draw the boss bigger.
    """
    if phases is None:
        return []
    if not isinstance(phases, list):
        raise BuildError(f"boss {bid}: phases must be a list")
    if len(phases) > MAX_PHASES:
        raise BuildError(f"boss {bid}: at most {MAX_PHASES} phases, got {len(phases)}")
    out = []
    previous = None
    previous_size = None
    banks = None
    for n, phase in enumerate(phases):
        if not isinstance(phase, dict):
            raise BuildError(f"boss {bid} phase {n}: must be an object")
        at = phase.get("at")
        if not isinstance(at, (int, float)) or isinstance(at, bool) or not 0.05 <= at <= 0.95:
            raise BuildError(f"boss {bid} phase {n}: at {at!r} must be a number 0.05..0.95")
        if previous is not None and at >= previous:
            raise BuildError(f"boss {bid} phase {n}: at {at!r} is not strictly below the previous "
                             f"phase's {previous!r}")
        previous = at
        phase_moves = phase.get("moves")
        if not isinstance(phase_moves, list) or not 1 <= len(phase_moves) <= 3:
            raise BuildError(f"boss {bid} phase {n}: moves must name 1..3 of the boss's own moves")
        for move in phase_moves:
            if move not in moves:
                raise BuildError(f"boss {bid} phase {n}: move {move!r} is not one of the boss's "
                                 f"own moves {moves}")
        field = phase.get("field")
        if field is not None and field not in PHASE_FIELDS:
            raise BuildError(f"boss {bid} phase {n}: field {field!r} is not one of "
                             f"{sorted(PHASE_FIELDS)}")
        tint = phase.get("tint")
        if tint is not None and (not isinstance(tint, list) or len(tint) != 4 or not all(
                isinstance(v, (int, float)) and not isinstance(v, bool) and 0 <= v <= 1
                for v in tint)):
            raise BuildError(f"boss {bid} phase {n}: tint must be four numbers 0..1")
        page = phase.get("page")
        if not isinstance(page, str) or not page.strip():
            raise BuildError(f"boss {bid} phase {n}: needs a page (the line it puts up)")
        music = phase.get("music")
        if music is not None:
            if banks is None:
                banks = battle_banks()
            if not isinstance(music, str) or music not in banks:
                raise BuildError(f"boss {bid} phase {n}: music {music!r} is not one of the "
                                 f"game's battle banks {sorted(banks)}")
        size = phase.get("size")
        if size is not None:
            if (not isinstance(size, (int, float)) or isinstance(size, bool)
                    or not 0.5 <= size <= 8 or abs(size * 10 - round(size * 10)) > 1e-9):
                raise BuildError(f"boss {bid} phase {n}: size {size!r} must be a number 0.5..8 "
                                 f"with at most one decimal")
            if previous_size is not None and size < previous_size:
                raise BuildError(f"boss {bid} phase {n}: size {size!r} is smaller than the previous "
                                 f"phase's {previous_size!r} (a boss only grows)")
            previous_size = size
        resolved = {"at": float(at), "moves": list(phase_moves)}
        if size is not None:
            resolved["size"] = float(size)
        if field is not None:
            resolved["field"] = field
        if tint is not None:
            resolved["tint"] = [float(v) for v in tint]
        if music is not None:
            resolved["music"] = music
        resolved["page"] = page.strip()
        out.append(resolved)
    return out


def screen_party_hp(screens, screen_id, half):
    screen = screens.get(str(screen_id))
    if not screen:
        raise BuildError(f"screen {screen_id} is not in field_encounters.json")
    lead = screen[0].get("name") if screen else None
    if lead != half:
        raise BuildError(f"screen {screen_id} fields {lead!r}, not the half {half!r} it is named for")
    total = 0
    for member in screen:
        hp = member.get("hp")
        if not is_int(hp) or hp <= 0:
            raise BuildError(f"screen {screen_id} member {member.get('name')!r} has no positive hp")
        total += hp
    return total


def resolve_boss(row, enemies, real_skills, authored_skills, screens):
    bid = row.get("id")
    if not isinstance(bid, str) or not bid.strip():
        raise BuildError(f"boss {bid!r} needs a string id")
    halves = row.get("halves")
    if not isinstance(halves, list) or len(halves) != 2:
        raise BuildError(f"boss {bid}: halves must name exactly two species")
    for half in halves:
        if half not in enemies:
            raise BuildError(f"boss {bid}: half {half!r} is not a real species (not in enemies.json)")
    body = row.get("body")
    if body not in halves:
        raise BuildError(f"boss {bid}: body {body!r} must be one of its halves")
    display = row.get("displayName")
    if not isinstance(display, str) or not display.strip():
        raise BuildError(f"boss {bid}: needs a displayName")
    level = row.get("level")
    if not is_int(level) or not 1 <= level <= 99:
        raise BuildError(f"boss {bid}: level {level!r} must be an integer 1..99")
    hp_screens = row.get("hpFromScreens")
    if not isinstance(hp_screens, list) or len(hp_screens) != len(halves):
        raise BuildError(f"boss {bid}: hpFromScreens must name one screen per half")
    hp = sum(screen_party_hp(screens, screen_id, half) for screen_id, half in zip(hp_screens, halves))
    scale_src = row.get("statScaleFromScreen")
    if not isinstance(scale_src, dict):
        raise BuildError(f"boss {bid}: statScaleFromScreen must be {{screen, delta}}")
    screen_id, delta = scale_src.get("screen"), scale_src.get("delta")
    screen = screens.get(str(screen_id))
    if not screen:
        raise BuildError(f"boss {bid}: stat scale screen {screen_id!r} is not in field_encounters.json")
    if screen[0].get("name") not in halves:
        raise BuildError(f"boss {bid}: stat scale screen {screen_id} is not one of its halves")
    base_scale = screen[0].get("stat_scale")
    if not is_int(base_scale) or not is_int(delta):
        raise BuildError(f"boss {bid}: the stat scale screen needs an integer stat_scale and an integer delta")
    stat_scale = base_scale + delta
    if not 1 <= stat_scale <= 64:
        raise BuildError(f"boss {bid}: resolved stat scale {stat_scale} is outside 1..64")
    moves = row.get("moves")
    if not isinstance(moves, list) or len(moves) != 3:
        raise BuildError(f"boss {bid}: moves must name attack, move_1 and move_2")
    for move in moves:
        if move not in real_skills and str(move) not in authored_skills:
            raise BuildError(f"boss {bid}: move {move!r} is not a real technique or an authored fusion skill")
    tint = row.get("tint")
    if not isinstance(tint, list) or len(tint) != 4 or not all(
            isinstance(v, (int, float)) and not isinstance(v, bool) and 0 <= v <= 1 for v in tint):
        raise BuildError(f"boss {bid}: tint must be four numbers 0..1")
    transform = row.get("transform")
    if transform not in TRANSFORMS:
        raise BuildError(f"boss {bid}: transform {transform!r} is not one of {sorted(TRANSFORMS)}")
    phases = resolve_phases(bid, row.get("phases"), moves)
    return bid, {
        "id": bid,
        "halves": list(halves),
        "body": body,
        "displayName": display.strip(),
        "level": level,
        "hp": hp,
        "statScale": stat_scale,
        "moves": list(moves),
        "tint": [float(v) for v in tint],
        "transform": transform,
        "phases": phases,
    }


def build():
    enemies = {e["enemy_id"]: e for e in load("enemies.json")["enemies"]}
    digimon = load("digimon.json")
    real_skills = {s["id"]: s for s in digimon["skills"]}
    fight_tech = load("fight_tech_table.json")
    screens = load("field_encounters.json").get("screens") or {}

    skills = {}
    for row in json.load(open(os.path.join(SRC, "fusion_skills.json"), encoding="utf-8")).get("skills", []):
        key, resolved = resolve_skill(row, real_skills, fight_tech)
        if key in skills:
            raise BuildError(f"duplicate authored skill id {key}")
        skills[key] = resolved

    bosses = {}
    for row in json.load(open(os.path.join(SRC, "fusion_bosses.json"), encoding="utf-8")).get("bosses", []):
        key, resolved = resolve_boss(row, enemies, real_skills, skills, screens)
        if key in bosses:
            raise BuildError(f"duplicate boss id {key}")
        bosses[key] = resolved

    return {"_comment": COMMENT, "bosses": bosses, "skills": skills}


def main():
    try:
        data = build()
    except BuildError as e:
        print("BUILD ERROR:", e)
        return 1
    text = json.dumps(data, indent=2, ensure_ascii=False)
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("web/fusion_bosses.json is up to date" if ok else
              "web/fusion_bosses.json is OUT OF DATE: run tools/build_fusion_bosses.py")
        return 0 if ok else 1
    open(OUT, "w", encoding="utf-8").write(text)
    for boss in data["bosses"].values():
        print(f"wrote {os.path.relpath(OUT, ROOT)}: {boss['id']} = {' + '.join(boss['halves'])} -> "
              f"{boss['displayName']} (HP {boss['hp']}, stat scale {boss['statScale']}, "
              f"moves {'/'.join(str(m) for m in boss['moves'])}, tint {boss['tint']})")
    for skill in data["skills"].values():
        print(f"  skill {skill['id']} {skill['name']}: power {skill['power']}, mp {skill['mp_cost']}, "
              f"{skill['element']} {skill['attack_category']}, clip {skill['clip']}, "
              f"effect {skill['effect']} ({skill['effect_id']}/{skill['effect_power']}) from row {skill['base']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
