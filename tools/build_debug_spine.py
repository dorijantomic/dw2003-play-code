#!/usr/bin/env python3
"""Build web/assets/data/debug_spine.json — the linear story spine the in-game
scene-skip debugger and the autonomous walkthrough test both consume.

Each entry is one master-ordinal beat ([0x8004b370], field-script-engine §WS4.6):
  { ordinal, ordHex, stage, name, prevOrdinal, eventCount, sayActors, clearFlags }

Sources (all decoded, no hand-data):
  - progress_ordinal.json   ordinal -> stage  (the play-order ladder)
  - manifest.json           stage  -> human name
  - scripted_battles.json   per-stage wstag events (say_actors + on_complete flags)

Do not hand-edit the output — rerun this tool.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, "web", "assets")
D = os.path.join(A, "data")


def load(p):
    with open(p) as f:
        return json.load(f)


def main():
    ladder = load(os.path.join(D, "progress_ordinal.json"))["ladder"]
    names = {m["id"]: m["name"] for m in load(os.path.join(A, "manifest.json"))["maps"]}
    sb = load(os.path.join(D, "scripted_battles.json"))

    # ordinal -> stage id (first stage that writes that ordinal)
    rows = []
    for beat in ladder:
        sid = "s%d" % beat["stage"]
        for o in beat["ordinals"]:
            rows.append((o, sid))
    rows.sort()

    spine = []
    prev = 0
    for ordinal, sid in rows:
        evs = sb.get(sid, {}).get("events", [])
        clear, actors = set(), set()
        for e in evs:
            for f in e.get("on_complete_setflags", []):
                # Only the writable STORED story banks (< 0x80) gate scene re-firing; banks
                # 0x80+ are virtual roster/ordinal predicates the FlagManager refuses to set.
                if (f["id"] >> 8) < 0x80:
                    clear.add(f["id"])
            for a in e.get("say_actors", []):
                actors.add(a)
        spine.append({
            "ordinal": ordinal,
            "ordHex": "0x%02x" % ordinal,
            "stage": sid,
            "name": names.get(sid, sid),
            "prevOrdinal": prev,
            "eventCount": len(evs),
            "sayActors": sorted(actors),
            "clearFlags": sorted(clear),
        })
        prev = ordinal

    out = os.path.join(D, "debug_spine.json")
    with open(out, "w") as f:
        json.dump({"_comment": "Generated by tools/build_debug_spine.py — do not hand-edit.",
                   "spine": spine}, f, indent=1)
    print("wrote", out, "(%d beats)" % len(spine))


if __name__ == "__main__":
    main()
