#!/usr/bin/env python3
"""Generate engine/dw3/item-names.ts — the REAL item display names/descriptions.

Source: ~/ddw3/lang_file/dw2003/eng/esitmnam.toml (403 names, string index ==
item id — verified: 43="Power Charge", 71="Life Plug", 92="Short Sword") and
esitminf.toml (descriptions, same indexing). These are the strings the game
itself renders in the shop/status/item screens; the ItemId enum names used
before ("PowerCharge", "LifePlug") are decomp identifiers, not display text.
"""

import os
import json
import re
from pathlib import Path

DDW3 = Path(os.environ.get("DDW3_DIR") or Path.home() / "ddw3")
OUT = Path(__file__).resolve().parent.parent / "engine/dw3/item-names.ts"


def parse_strings(toml_path: Path) -> list[str]:
    return re.findall(r'^\t"(.*)",?$', toml_path.read_text(), re.M)


def main() -> int:
    names = parse_strings(DDW3 / "lang_file/dw2003/eng/esitmnam.toml")
    descs = parse_strings(DDW3 / "lang_file/dw2003/eng/esitminf.toml")
    lines = [
        "// engine/dw3/item-names.ts — GENERATED by tools/build_item_names.py; do not edit.",
        "// Real item display names/descriptions from lang_file/dw2003/eng/esitmnam.toml /",
        "// esitminf.toml (string index == item id).",
        "",
        "export const ITEM_NAMES: Record<number, string> = {",
    ]
    for i, n in enumerate(names):
        if i == 0 or not n:
            continue
        lines.append(f"  {i}: {json.dumps(n)},")
    lines += ["};", "", "export const ITEM_DESCS: Record<number, string> = {"]
    for i, d in enumerate(descs):
        if i == 0 or not d:
            continue
        lines.append(f"  {i}: {json.dumps(d)},")
    lines += ["};", ""]
    OUT.write_text("\n".join(lines))
    print(f"item-names.ts: {sum(1 for n in names[1:] if n)} names, "
          f"{sum(1 for d in descs[1:] if d)} descs -> {OUT}")
    return 0


if __name__ == "__main__":
    return_code = main()
    raise SystemExit(return_code)
