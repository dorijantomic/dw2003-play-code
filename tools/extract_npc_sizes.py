#!/usr/bin/env python3
"""Extract the fieldstg half-sprite-size table used by the confirm probe.

The field-character constructor stores `(size(kind) >> 1)` into entity+0x80; for
an NPC `kind` is its `npc_id`. F0x8008E210's box test uses that half-width, and
`size()` is the byte table at RAM 0x8009A458 (FIELDSTG.PRO file 0x177A8, overlay
load base 0x80082CB0). Claim world-q001-confirm-probe-box-rule-2026-09-13.

Writes engine/dw3/npc-sizes.ts. Run from the repository root:

    .venv/bin/python3 tools/extract_npc_sizes.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

TABLE_BASE = 0x8009A458      # size byte table (fieldstg data)
LOAD_BASE = 0x80082CB0       # FIELDSTG.PRO overlay load base
FIELDSTG_IDX = 358           # LBA file index of FIELDSTG.PRO
TABLE_LEN = 512


def main() -> int:
    from extract_point_sprites import Disc, DISC  # existing disc reader

    image = Disc(DISC).file(FIELDSTG_IDX)
    off = TABLE_BASE - LOAD_BASE
    sizes = list(image[off:off + TABLE_LEN])
    if len(sizes) != TABLE_LEN:
        raise SystemExit(f"FIELDSTG.PRO too short for the table at {off:#x}")
    if max(sizes) == 0:
        raise SystemExit("the size table read as all zero; wrong offset or image")

    out: list[str] = [
        "// Generated by tools/extract_npc_sizes.py — the fieldstg half-sprite-size table",
        "// at RAM 0x800A9DF8/0x800920F8-backed 0x8009A458 (FIELDSTG.PRO file 0x177A8),",
        "// indexed by the constructor kind: for an NPC that kind is its npc_id. The",
        "// constructor stores `(size(kind) >> 1)` into entity+0x80, which the confirm",
        "// probe F0x8008E210 uses as the box half-width. Claim",
        "// world-q001-confirm-probe-box-rule-2026-09-13.",
        "",
        "export const NPC_SIZE_TABLE_OFFSET = 0x177a8;",
        "",
        "const NPC_SIZE_BYTES: readonly number[] = [",
    ]
    for i in range(0, TABLE_LEN, 16):
        out.append("  " + ", ".join(str(v) for v in sizes[i:i + 16]) + ",")
    out += [
        "];",
        "",
        "/** entity+0x80 for a constructor kind, or null when the kind is outside the",
        " *  extracted table (the native would read past it). */",
        "export function npcHalfWidth(kind: number | null | undefined): number | null {",
        "  if (kind == null || !Number.isFinite(kind)) return null;",
        "  const i = Math.trunc(kind);",
        "  if (i < 0 || i >= NPC_SIZE_BYTES.length) return null;",
        "  return NPC_SIZE_BYTES[i]! >> 1;",
        "}",
        "",
    ]
    dest = ROOT / "engine/dw3/npc-sizes.ts"
    dest.write_text("\n".join(out))
    print(f"wrote {dest} ({TABLE_LEN} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
