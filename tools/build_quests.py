#!/usr/bin/env python3
"""Build web/quests.json from its sources: data/authored/quests/legacy.json plus every pack_*.py (docs/quests-bible.md).

    python3 tools/build_quests.py            writes web/quests.json and prints what it holds
    python3 tools/build_quests.py --check    builds in memory and fails if web/quests.json is out of date

Do not edit web/quests.json by hand. Quest ids are append-only: progress is stored by id.
"""
import collections
import importlib
import json
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "data", "authored", "quests")
OUT = os.path.join(ROOT, "web", "quests.json")
sys.path.insert(0, SRC)

COMMENT = ("Extra quests (new content, not part of the shipped game). GENERATED by tools/build_quests.py from "
           "data/authored/quests/ - edit the sources, not this file. Stage lists name BOTH worlds where a place exists as a "
           "normal and a post-game version. See docs/quests-bible.md.")


def main():
    import dsl
    legacy = json.load(open(os.path.join(SRC, "legacy.json"), encoding="utf-8"))["quests"]
    packs = sorted(f[:-3] for f in os.listdir(SRC) if f.startswith("pack_") and f.endswith(".py"))
    quests, where = list(legacy), {q["id"]: "legacy" for q in legacy}
    per_pack = collections.OrderedDict([("legacy", len(legacy))])
    try:
        for name in packs:
            mod = importlib.import_module(name)
            for q in mod.QUESTS:
                if q["id"] in where:
                    raise dsl.BuildError(f"duplicate quest id {q['id']!r} (in {name} and {where[q['id']]})")
                where[q["id"]] = name
                quests.append(q)
            per_pack[name] = len(mod.QUESTS)
    except dsl.BuildError as e:
        print("BUILD ERROR:", e)
        return 1
    if dsl.PROBLEMS:
        print(f"{len(dsl.PROBLEMS)} problem(s) in the packs:")
        for p in dsl.PROBLEMS:
            print("  -", p)
        return 1
    shipped = {l.strip() for l in open(os.path.join(SRC, "shipped.txt"), encoding="utf-8") if l.strip() and not l.startswith("#")}
    drafts = [q["id"] for q in quests if where[q["id"]] != "legacy" and q["id"] not in shipped]
    quests = [q for q in quests if q["id"] not in set(drafts)]
    for q in quests:                      # a shipped quest never waits on a draft
        u = q.get("unlock") or {}
        if u.get("done") in drafts:
            del u["done"]
        r = q.get("requires") or {}
        if r.get("done") in drafts:
            del r["done"]
            if not r:
                del q["requires"]
    text = json.dumps({"_comment": COMMENT, "quests": quests}, indent=2, ensure_ascii=False)
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("web/quests.json is up to date" if ok else "web/quests.json is OUT OF DATE: run tools/build_quests.py")
        return 0 if ok else 1
    open(OUT, "w", encoding="utf-8").write(text)
    kinds = collections.Counter(o["type"] for q in quests for o in q["objectives"])
    scenes = sum(1 for q in quests if q.get("offer", {}).get("scene"))
    print(f"wrote {OUT}: {len(quests)} quests ({', '.join(f'{k} {v}' for k, v in per_pack.items())})")
    print("objectives:", ", ".join(f"{k} {v}" for k, v in sorted(kinds.items())))
    print(f"{scenes} quests have a walking offer scene; {sum(1 for q in quests if q.get('reward', {}).get('items'))} give an item")
    return 0


if __name__ == "__main__":
    sys.exit(main())
