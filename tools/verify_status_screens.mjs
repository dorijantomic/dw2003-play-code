import { chromium } from "playwright";
import { baseUrl } from "./verify-base-url.mjs";
const OUT = process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1100, height: 760 } });
p.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await p.goto(`${baseUrl(8742)}/ui-lab.html`);
await p.waitForTimeout(4000);
const f = p.frames().find((x) => x.url().includes("index.html")) ?? p.mainFrame();
await f.evaluate(() => window.__labOpen("menu"));
await p.waitForTimeout(600);
const canvas = await f.$("canvas"); await canvas?.click();
const shot = async (n) => { const el = await f.$("canvas"); await el.screenshot({ path: `${OUT}/${n}.png` }); };
const key = async (k, n=1) => { for (let i=0;i<n;i++){ await p.keyboard.press(k); await p.waitForTimeout(150);} };
await key("ArrowDown", 4); await key("Enter"); await p.waitForTimeout(600);
await shot("ours-choose-digimon");
await key("Enter"); await p.waitForTimeout(700);
await shot("ours-status-sheet");
await key("Enter"); await p.waitForTimeout(700);
await shot("ours-choose-digivolve");
console.log(await f.evaluate(() => ({ screen: window.__menu?.screen, step: window.__menu?.detailStep })));
await b.close();
