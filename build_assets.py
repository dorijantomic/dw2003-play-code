# 8-row sheet: includes all diagonal directions. *-right rows are generated by mirroring
# their *-left counterparts. Used for both characters and NPCs — many "NPC"-category
# sprites have real decoded down-left/up-left frame data too (decode_sprite_anims.py), and
# the down-right/up-right mirror below is computed unconditionally whenever it exists; the
# old 4-row NPC_ROW_ORDER (down/left/right/up only) discarded that data at bake time, so a
# diagonally-walking NPC fell back to a sideways cardinal frame (_DIR_FALLBACK in game.js)
# instead of a real diagonal pose — same underlying frames, just never reachable.
CHAR_ROW_ORDER = ["down", "down-left", "left", "right", "up-left", "up", "down-right", "up-right"]
NPC_ROW_ORDER = CHAR_ROW_ORDER

# The right-hand facings — the ones the original mirrors (entity+0x60 >= 5,
# fieldstg.s:12892-12895). Their rows carry mirrored PIXELS, so the baked X
# placement reflects the offset+width pair instead of adding it.
MIRRORED_DIRS = {"right", "down-right", "up-right"}


# ── Real frame layouts (source of truth) ────────────────────────────────────────
# The per-sprite `dirs` lists above are hand-authored and 68/168 had drifted from the
# real game data (wrong stand frame, or entirely wrong frames → wrong sprite on screen).
# The authoritative layout is decoded straight from each sprite's animation .bin files by
# tools/decode_sprite_anims.py. We run it once and let the real layout OVERRIDE the
# authored one per-direction (authored only fills a direction the decode lacks). Verified
# data-driven: the decoder matches every starter sprite; see
# docs/research/2026-06-23-opening-animation-follower-parity-audit.md §sprite-export.
_REAL_DIRS_CACHE = None
def _real_dirs() -> dict:
    global _REAL_DIRS_CACHE
    if _REAL_DIRS_CACHE is None:
        result = subprocess.run(
            [sys.executable, str(Path(__file__).parent / "tools/decode_sprite_anims.py")],
            capture_output=True, text=True,
        )
        if result.returncode != 0:
            print("  ! decode_sprite_anims failed; falling back to authored dirs")
            print(result.stderr[-500:])
            _REAL_DIRS_CACHE = {}
        else:
            _REAL_DIRS_CACHE = json.loads(result.stdout)
    return _REAL_DIRS_CACHE


_DEFAULT_FRAME_TICKS = 8  # matches decode_sprite_anims._DEFAULT_DURATION


def _bottom_shift(y_offset: int, frame_height: int) -> int:
    """Where the billboard quad's BOTTOM row sits relative to the actor's ground screen
    row: the frame's registered Y offset (frame-list record word 4 -> entity+0xE0) plus
    the frame's own height (entity+0xE6, the TIM header's height).

    The original draws the quad's top row at `screenY + yOffset`
    (fieldstg.s:12919-12940), so `yOffset + height` is its bottom edge relative to that
    same row — the one number the browser renderer needs, because its baked sheets sit
    bottom-aligned on the ground row instead of registered per frame. Same formula as
    engine/systems/field-billboard-anchor.ts's `billboardBottomShift`, which
    tests/field-billboard-anchor.test.js pins these numbers against.
    """
    return y_offset + frame_height


def build_sheet(char: dict, row_order: list[str] = NPC_ROW_ORDER) -> dict:
    src = SPRITES / char["id"]
    # Real .bin layout wins; authored dirs fill any direction the decode doesn't provide.
    real_entry = _real_dirs().get(char["id"], {})
    real = real_entry.get("frames", {})
    real_durations = real_entry.get("durations", {})
    real_offsets = real_entry.get("offsets", {})
    dirs = {**char["dirs"], **real}
    frames: dict[str, list] = {}
    durations: dict[str, list] = {}
    offsets: dict[str, list] = {}
    bottoms: dict[str, list] = {}
    for direction, idxs in dirs.items():
        frames[direction] = [Image.open(src / f"{i}.png").convert("RGBA") for i in idxs]
        durations[direction] = real_durations.get(direction) or [_DEFAULT_FRAME_TICKS] * len(idxs)
        offs = real_offsets.get(direction)
        # Every field-sprite frame list on the disc carries the billboard's own
        # registration (frame-list record words 3 and 4 — decode_sprite_anims reads
        # them with the original's single 4-word walk). A row without it is a decode
        # gap, not a licence to guess: fail the build rather than place the frame by
        # its bounding box.
        if not offs or len(offs) != len(idxs):
            raise ValueError(
                f"{char['id']}/{direction}: {len(idxs)} frames but "
                f"{len(offs) if offs else 0} billboard registrations from the disc"
            )
        offsets[direction] = offs
        bottoms[direction] = [_bottom_shift(off[1], f.height)
                             for off, f in zip(offs, frames[direction])]

    # Generate mirrored rows from their left-side counterparts (timing is identical — the
    # original engine mirrors the sprite, not the animation clock). The mirror reflects
    # the offset+width pair, not just the pixels (F0x8008f52c: x0 = screenX − (E4 + DC)).
    frames["right"] = [ImageOps.mirror(f) for f in frames["left"]]
    durations["right"] = durations["left"]
    offsets["right"] = offsets["left"]
    bottoms["right"] = bottoms["left"]
    if "down-left" in frames:
        frames["down-right"] = [ImageOps.mirror(f) for f in frames["down-left"]]
        durations["down-right"] = durations["down-left"]
        offsets["down-right"] = offsets["down-left"]
        bottoms["down-right"] = bottoms["down-left"]
    if "up-left" in frames:
        frames["up-right"] = [ImageOps.mirror(f) for f in frames["up-left"]]
        durations["up-right"] = durations["up-left"]
        offsets["up-right"] = offsets["up-left"]
        bottoms["up-right"] = bottoms["up-left"]

    # Widen cells where the authentic per-frame offsets would push content past a
    # cell edge. The renderer draws the CELL centered on the actor anchor
    # (drawSprite: x − frameW/2), so reproducing the original billboard
    # (x0 = screenX + DC; mirrored x0 = screenX − (E4 + DC)) means content left
    # edge = frameW/2 + DC (left-side rows) or frameW/2 − DC − w (mirrored rows).
    # Both stay inside the cell iff cellW ≥ 2·max(DC + w, −DC).
    need = cell_w = max(f.width for fs in frames.values() for f in fs)
    for direction, offs in offsets.items():
        for (x, _y), f in zip(offs, frames[direction]):
            need = max(need, 2 * max(x + f.width, -x))
    cell_w = need
    n = max(len(f) for f in frames.values())
    cell_h = max(f.height for fs in frames.values() for f in fs)

    sheet = Image.new("RGBA", (cell_w * n, cell_h * len(row_order)))
    counts = {}
    frame_durations = {}
    frame_bottoms = {}
    for row, direction in enumerate(row_order):
        # Fall back to "down" row if a direction is missing (shouldn't happen for characters)
        source = direction if direction in frames else "down"
        fs = frames[source]
        ds = durations.get(source) or durations["down"]
        os_ = offsets[source]
        counts[direction] = len(fs)
        frame_durations[direction] = ds
        frame_bottoms[direction] = bottoms[source]
        mirrored = direction in MIRRORED_DIRS
        for col, f in enumerate(fs):
            x_off = os_[col][0]
            if mirrored:
                x = col * cell_w + round(cell_w / 2 - x_off - f.width)
            else:
                x = col * cell_w + round(cell_w / 2 + x_off)
            y = row * cell_h + (cell_h - f.height)
            sheet.alpha_composite(f, (x, y))

    out_path = OUT / "sprites" / f"{char['id']}.png"
    sheet.save(out_path)
    entry = {
        "id": char["id"], "name": char["name"],
        "sheet": f"assets/sprites/{char['id']}.png",
        "frameW": cell_w, "frameH": cell_h,
        "rows": row_order, "frameCounts": counts,
        "frameDurations": frame_durations,
        "frameBottomShift": frame_bottoms,
    }
    if char.get("starter"):
        entry["starter"] = True

    clips = _build_clip_strip(char["id"], src, real_entry.get("clips", {}))
    if clips:
        entry.update(clips)

    return entry


def _build_clip_strip(char_id: str, src: Path, clips_data: dict) -> dict | None:
    """Bake a sprite's SETANIM clip directory into a flat, deduped frame strip.

    `clips_data` (from tools/decode_sprite_anims.py, real per-clip data — see
    docs/research/field/field-actor-anim-engine.md) maps clip_id -> direction ->
    {"frames": [frame_idx,...], "durations": [ticks,...], "xoffsets"/"yoffsets": [...]}.
    Rather than adding a row per clip to the main direction sheet (most clips reuse only a
    handful of frames), every frame image any clip actually references is deduped into one
    flat horizontal strip; the manifest stores each clip/direction as
    {"cols": [...], "durations": [...], "bottoms": [...]} indexing into that strip.

    X is BAKED (content left = cellW/2 + DC, so drawing the cell centred on the actor
    anchor reproduces x0 = screenX + DC and, mirrored, screenX − (E4 + DC) for free).
    Y is not bakeable — the strip's cells are bottom-aligned on the actor's ground row, and
    the original registers each frame's quad top at `screenY + yOffset`, which puts its
    bottom at `yOffset + height` below that row — so `bottoms` carries that number per
    frame and the renderer adds it.
    """
    if not clips_data:
        return None

    # Dedup key includes the frame's own billboard X offset (frame-list record word 3,
    # entity+0xDC — claims world-q007-*-001, verified 2026-09-05): the same frame
    # image in two directions can carry different offsets, so it must occupy two
    # strip cells.
    frame_order: list[tuple[int, int]] = []
    seen: set[tuple[int, int]] = set()
    heights: dict[int, int] = {}
    for per_dir in clips_data.values():
        for info in per_dir.values():
            xoffs = info.get("xoffsets")
            if not xoffs or len(xoffs) != len(info["frames"]):
                raise ValueError(
                    f"{char_id} clip frame list of {len(info['frames'])} frames carries "
                    f"{len(xoffs) if xoffs else 0} billboard X registrations from the disc"
                )
            for j, f in enumerate(info["frames"]):
                heights.setdefault(f, Image.open(src / f"{f}.png").size[1])
                key = (f, xoffs[j])
                if key not in seen:
                    seen.add(key)
                    frame_order.append(key)
    if not frame_order:
        return None

    col_of = {fx: i for i, fx in enumerate(frame_order)}
    images = [Image.open(src / f"{i}.png").convert("RGBA") for i, _ in frame_order]

    # Widen cells where an authentic offset would push content past a cell edge:
    # content left = cellW/2 + DC must satisfy 0 ≤ · ≤ cellW − w for every frame.
    cell_w = max(im.width for im in images)
    for im, x in zip(images, (x for _, x in frame_order)):
        cell_w = max(cell_w, 2 * max(x + im.width, -x))
    cell_h = max(im.height for im in images)

    # Mirroring for right-facing directions happens live at draw time, symmetric around the
    # cell's own center — and since the baked offset is part of the baked content position,
    # the mirror reflects it for free (x0 = screenX − (E4 + DC)), exactly as the original
    # does. Y has no mirror branch in the original (fieldstg.s:12919-12940), so the baked
    # strip's own row is used unchanged for both facings.
    strip = Image.new("RGBA", (cell_w * len(images), cell_h))
    for col, (im, (f, x)) in enumerate(zip(images, frame_order)):
        bx = round(cell_w / 2 + x)
        strip.alpha_composite(im, (col * cell_w + bx, cell_h - im.height))

    clips_dir = OUT / "sprites" / "clips"
    clips_dir.mkdir(parents=True, exist_ok=True)
    strip.save(clips_dir / f"{char_id}.png")

    clips_out = {}
    for clip_id, per_dir in clips_data.items():
        entry_out = {}
        for direction, info in per_dir.items():
            xoffs = info["xoffsets"]
            yoffs = info.get("yoffsets")
            if not yoffs or len(yoffs) != len(info["frames"]):
                raise ValueError(
                    f"{char_id} clip {clip_id}/{direction} carries "
                    f"{len(yoffs) if yoffs else 0} billboard Y registrations for "
                    f"{len(info['frames'])} frames"
                )
            cols, bottoms = [], []
            for j, f in enumerate(info["frames"]):
                col = col_of[(f, xoffs[j])]
                cols.append(col)
                bottoms.append(_bottom_shift(yoffs[j], images[col].height))
            entry_out[direction] = {
                "cols": cols, "durations": info["durations"], "bottoms": bottoms,
            }
        clips_out[clip_id] = entry_out

    return {
        "clipSheet": f"assets/sprites/clips/{char_id}.png",
        "clipFrameW": cell_w,
        "clipFrameH": cell_h,
        "clips": clips_out,
    }


def build_map(m: dict) -> dict:
    asset_id = m.get("assetSource", m["id"])
    out_path = OUT / "maps" / f"{asset_id}.png"
    if not out_path.exists():  # cached; delete the PNG to force a rebuild
        if asset_id != m["id"]:
            raise FileNotFoundError(
                f"alias {m['id']} requires base map asset {out_path}"
            )
        if m.get("bgSource") == "bg01":
            decode_bg01(m["id"]).save(out_path)
        else:
            subprocess.run(
                [sys.executable, "tools/stitch-map.py",
                 f"map/dw2003/z_stage/{m['id']}pack.toml", "-o", str(out_path)],
                cwd=DDW3, check=True, capture_output=True,
            )
    img = Image.open(out_path)
    coll = OUT / "collision" / f"{asset_id}.json"
    entry = {
        "id": m["id"], "name": m["name"],
        "image": f"assets/maps/{asset_id}.png",
        "width": img.width, "height": img.height,
        "music": m.get("music"),
    }
    if asset_id != m["id"]:
        entry["assetSource"] = asset_id
    for key in ("fixedViewportBackground", "cutsceneCameraCenter"):
        if key in m:
            entry[key] = m[key]
    if coll.exists():
        entry["collision"] = f"assets/collision/{asset_id}.json"
    return entry


