#!/usr/bin/env python3
"""Generate engine/dw3/item-data.ts — the REAL consumable/booster item records.

Source: web/assets/data/item_effects.json (tools/extract_item_effects.py), the
decoded master item table D0x80041844 + consumable-effect table D0x8005cb54
(docs/research/ui/item-system-decoded-2026-07-10.md). This replaces the
hand-authored placeholder ITEMS array that used to live in engine/dw3/items.ts
(falsified values: e.g. PowerCharge was guessed 200 HP; real value is 500).

Emitted rows: category "consumable" (ids 43-91) and "booster" (361-394).
Equipment/accessories come from equipment.ts; key items are name-only.
Fields: id, name (decomp enum id; display name overlaid from item-names.ts),
effect (decoded vocabulary: hp/stat_*/elem_*/tp/battle/booster), value,
price (buy, 0 = not sold), sell (real sell price — NOT always buy/2:
TrainChips are buy 0 / sell 400+).

`itemClass` and `selector` are the effect record's OWN two bytes, so behaviour
never has to be re-derived from the vocabulary above:
  * `itemClass` = byte +0 of the 12-byte pair row at 0x8005cb54 - the low byte of
    `effect_raw[0]`. Bit 0 is what the original's "may this be used here" test
    reads (pro/ststatus.s `lbu` + `andi $v1, 0x1` at the ITEMS page's choose
    branch), and it is 1 for the field-usable chips and charges and 0 for the
    battle disks (2) and the booster packs (4).
  * `selector` = byte +1 of the same row, the high byte of `effect_raw[0]`. This
    is the code F0x8008F584 dispatches on (see engine/dw3/item-effect.ts);
    0x00 does nothing, 0x01 heals, 0x02..0x10 raise a stat or a tolerance and
    0x11 grants TP.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "web/assets/data/item_effects.json"
OUT = ROOT / "engine/dw3/item-data.ts"


def main() -> None:
    items = json.loads(SRC.read_text())["items"]
    rows = []
    for it in items:
        if it["category"] == "consumable":
            effect = it["effect"] or "battle"
            value = it.get("value") or 0
        elif it["category"] == "booster":
            effect = "booster"
            value = 0
        else:
            continue
        raw = it.get("effect_raw") or [0, 0]
        item_class, selector = raw[0] & 0xFF, (raw[0] >> 8) & 0xFF
        rows.append(
            f'  {{ id: {it["id"]}, name: "{it["name"]}", effect: "{effect}", '
            f'value: {value}, price: {it["buy"]}, sell: {it["sell"]}, '
            f'itemClass: {item_class}, selector: {selector} }},'
        )

    lines = [
        "// engine/dw3/item-data.ts — GENERATED by tools/build_item_data.py; do not edit.",
        "// Decoded consumable/booster records from the master item table (D0x80041844)",
        "// and consumable-effect table (D0x8005cb54) via web/assets/data/item_effects.json.",
        "// See docs/research/ui/item-system-decoded-2026-07-10.md.",
        "",
        "export interface ItemDataRow {",
        "  id: number;",
        "  name: string;",
        "  effect: string;",
        "  value: number;",
        "  price: number; // buy price in bits; 0 = not sold in shops",
        "  sell: number;  // real sell price (not always price/2)",
        "  /** Effect record byte +0: bit 0 = the original offers this item in the field. */",
        "  itemClass: number;",
        "  /** Effect record byte +1: the code the field applier dispatches on. */",
        "  selector: number;",
        "}",
        "",
        "export const ITEM_DATA: ItemDataRow[] = [",
        *rows,
        "];",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"Wrote {len(rows)} item records -> {OUT}")


if __name__ == "__main__":
    main()
