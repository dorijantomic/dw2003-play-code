// Catalog-driven route census. Read-only assets; output stays in docs/generated.
import { readFileSync, writeFileSync } from 'node:fs';
import { ITEM_BY_ID, itemUsableInField, itemUsableInBattle } from '../engine/dw3/items.ts';
import { itemReaders } from './item-readers.mjs';
const census=itemReaders();
const read=name=>JSON.parse(readFileSync(`web/assets/data/${name}.json`,'utf8'));
const shipped=read('item_effects').items;
const obtain=read('item_obtain_index').items;
const fight=readFileSync('web/assets/native/screens/pro_fightstg.bin');
const rows=shipped.map(row=>{
 const sources=obtain[String(row.id)]?.sources??[];
 return {
  readers:census.readers.filter(r=>r.itemId===row.id).map(({itemId,...r})=>r),
  readerDecision:census.readers.some(r=>r.itemId===row.id&&r.kind!=="inventory_directory")?{status:"readers_found"}:{status:"no_special_reader_in_searched_corpus",search:"readerSearch"},
  id:row.id,name:ITEM_BY_ID[row.id].name,category:row.category,
  fieldUse:itemUsableInField(row.id)?{consumer:'engine/dw3/items.ts useItem',selector:ITEM_BY_ID[row.id].selector}:null,
  pauseUse:itemUsableInField(row.id)?{consumer:'engine/dw3/ui/native/pause-bag.ts itemsApplyEffect',selector:ITEM_BY_ID[row.id].selector}:null,
  battleUse:itemUsableInBattle(row.id)?{consumer:row.id<66?'web/battle.js charge branch':'engine/dw3/battle-items.ts useBattleItem',handler:`0x${fight.readUInt32LE(0x80082f1c-0x80082cb0+(row.id-43)*4).toString(16)}`} :null,
  equip:['equipment','accessory'].includes(row.category)?'engine/dw3/equipment.ts equipApplyRecord':null,
  shops:sources.filter(s=>s.kind==='shop'),
  gifts:sources.filter(s=>s.kind==='talk'),
  storyGrants:sources.filter(s=>s.kind==='cutscene'||s.kind==='native'),
  drops:sources.filter(s=>s.kind==='drop'),
 };
});
const output={
 scope:'402 shipped item records. Menu/equip routes, raw extracted stage readers, converted possession ops, native immediate checks and decoded booster opening/reward members. Negative decisions are scoped searches, not proof that arbitrary original-code reads are absent.',
 readerSearch:census.search,
 evidence:['docs/research/ui/item-system-decoded-2026-07-10.md','docs/research/items/item-store-shared-system-2026-10-03.md','docs/research/battle/battle-items-decoded-2026-07-10.md'],
 limits:['Gift means an indexed NPC talk grant, not a claim that another gift screen is absent.','A null use route means no menu admission; key-item possession gates and booster opening have separate consumers.','Shop 30 has no mapped merchant; native grants retain the attribution quality of item_obtain_index.json.','ITEM-Q001 requires exhaustive original-code reachability beyond this static and extracted-reader census; do not close it from these counts alone.'],
 items:rows,
};
const boosterIds=read('card_boosters').sets.map(s=>s.setId);
const moduleBody='// Generated by tools/report_item_routes.mjs from the decoded stcrdshp set table.\nexport const BOOSTER_ITEM_IDS = '+JSON.stringify(boosterIds)+' as const;\n';
if(process.argv.includes('--check')) {
 if(readFileSync('engine/dw3/booster-items.ts','utf8')!==moduleBody) throw new Error('booster item members stale');
} else writeFileSync('engine/dw3/booster-items.ts',moduleBody);
const body=JSON.stringify(output,null,2)+'\n';
const path='docs/generated/item-routes.json';
if(process.argv.includes('--check')) {
 if(readFileSync(path,'utf8')!==body) throw new Error('item route census is stale');
} else writeFileSync(path,body);
console.log(`item route census: ${rows.length} members; field ${rows.filter(r=>r.fieldUse).length}; battle ${rows.filter(r=>r.battleUse).length}; equip ${rows.filter(r=>r.equip).length}`);
