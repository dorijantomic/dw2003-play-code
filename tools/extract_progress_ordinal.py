#!/usr/bin/env python3
"""Extract the master story-progress ORDINAL ladder ([0x8004b370]) from the wstag
overlays → web/assets/data/progress_ordinal.json.

`0x8004b370` is the single linear story-progress ordinal (1 → 0x2d): each scripted
beat's own overlay writes its unique value on completion via a leaf setter of the
shape `li $v0,N ; ... ; sw $v0,-0x4c90($v1)`. Stage-entry handlers gate on
`b370 == predecessor_ordinal`, so the value order = the literal play order. See
docs/research/scripting/field-script-engine-verified.md §WS4.6.

Method: in each wstagNNN.s, find every store `sw $vX, -0x4c90(...)` (the `.word`
low half is 0xb370, opcode sw, any base) and read the nearest preceding immediate
load `li $vX, N` (addiu $vX,$zr,N) of the SAME register, within a small window.
Computed/register stores with no immediate (e.g. resets to 0 via a register copy)
are skipped — they are not ordinal milestones.

Run: python3 tools/extract_progress_ordinal.py   (writes the json + prints the ladder)
"""
import os
import json
import re
from pathlib import Path

ASM_DIR = Path(os.environ.get("DDW3_DIR") or Path.home() / "ddw3") / "asm/dw2003/pro"
OUT = Path(__file__).resolve().parent.parent / "web/assets/data/progress_ordinal.json"

WORD_RE = re.compile(r"\.word\s+0x([0-9a-fA-F]{8})")
LOOKBACK = 5  # instructions to scan upward for the li that feeds the store


def words_of(path):
    """Return [(label_addr:int, word:int)] for a .s file, in order."""
    out = []
    for line in path.read_text().splitlines():
        m = WORD_RE.search(line)
        if not m:
            continue
        out.append(int(m.group(1), 16))
    return out


def decode_sw_b370(w):
    """If w is `sw $rt, 0xb370(base)`, return rt; else None."""
    if (w >> 26) != 0x2B:            # opcode sw
        return None
    if (w & 0xFFFF) != 0xB370:        # imm = -0x4c90 = 0xb370
        return None
    return (w >> 16) & 0x1F           # rt (stored register)


def decode_li(w, rt):
    """If w is `li $rt, N` (addiu $rt,$zr,N), return N; else None."""
    if (w >> 26) != 0x09:            # opcode addiu
        return None
    if ((w >> 21) & 0x1F) != 0:       # rs must be $zr
        return None
    if ((w >> 16) & 0x1F) != rt:      # rt must match the stored reg
        return None
    imm = w & 0xFFFF
    return imm - 0x10000 if imm & 0x8000 else imm


def main():
    ladder = {}   # stage_int -> sorted list of ordinals it writes
    for p in sorted(ASM_DIR.glob("wstag*.s")):
        m = re.match(r"wstag(\d+)$", p.stem)
        if not m:
            continue
        stage = int(m.group(1))
        words = words_of(p)
        vals = set()
        for i, w in enumerate(words):
            rt = decode_sw_b370(w)
            if rt is None:
                continue
            for j in range(i - 1, max(-1, i - 1 - LOOKBACK), -1):
                n = decode_li(words[j], rt)
                if n is not None:
                    if 0 <= n <= 0x3FF:   # plausible ordinal (incl 0x300 free-roam sentinel)
                        vals.add(n)
                    break
        if vals:
            ladder[stage] = sorted(vals)

    # Order by the smallest ordinal each stage writes = the play-order spine.
    by_order = sorted(ladder.items(), key=lambda kv: (kv[1][0], kv[0]))
    data = {
        "_comment": ("Master story-progress ordinal [0x8004b370] per stage, extracted "
                     "from wstagNNN.s leaf setters (li $v0,N ; sw $v0,-0x4c90). The value "
                     "order is the literal play order; stage-entry handlers gate on "
                     "b370==predecessor. See field-script-engine-verified.md §WS4.6. "
                     "Generated by tools/extract_progress_ordinal.py — do not hand-edit."),
        "ladder": [{"stage": s, "ordinals": v} for s, v in by_order],
        "by_stage": {str(s): v for s, v in ladder.items()},
    }
    OUT.write_text(json.dumps(data, indent=1) + "\n")
    print(f"wrote {OUT} — {len(ladder)} stages")
    for s, v in by_order:
        marks = "/".join(f"0x{x:02x}" for x in v)
        print(f"  0x{v[0]:02x}  s{s:<4} {marks}")


if __name__ == "__main__":
    main()
