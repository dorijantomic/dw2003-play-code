#!/usr/bin/env python3
"""Copy STDWTITL's movie table whole: every row's disc file, frame count and
where the movie sends the player when it ends.

Source: pro/stdwtitl.s (overlay RAM base 0x80082cb0, so file offset = RAM -
0x80082cb0). The table is at RAM 0x80087C98 = file 0x4FE8 and is twelve 12-byte
rows read by F0x80083CC0 (`pro/stdwtitl.s:1114-1190`) as
`(row + 0) , (row + 4), (row + 8)`:

  row+0  the movie's DISC FILE INDEX.  `F0x80083944` hands it to the resident
         loader `*(s32(**)(?,?,?,?))0x8004874C(index, 0, &obj->+0x50)`
         (exe-decomp/stdwtitl_c/F0x80083944.c:39), i.e. LoadFile.
  row+4  the movie's FRAME COUNT.  `web/assets/data/stdwtitl_ui.json`
         `title_menu.movie_display.frames` is 1776, which is row 0 AND row 1's
         +4 (0x6f0) - the two opening movies, and `web/title-movie.js` ends a
         movie when the shown-picture counter reaches it.
  row+8  the RETURN SELECTOR the movie object launches when it is gone:
         `F0x80083CC0` state 1 calls `*(?**)0x8004B440(row->+8, 0)` then
         `obj->unk28(obj, 2)` (pro/stdwtitl.s:1160-1170).

Two things sit on top of row+8, and both are in the same routine:

  * movie 2 at master ordinal 0x2D stores 0x276 instead of the row's own 0x0207
    (`pro/stdwtitl.s:1180-1198`, the `li $v0, 0x2d` compare at :1129-1130).
  * movie 11 is chosen by LANGUAGE, not by the launch code, so it has no row
    here: three triples at file 0x5074 / 0x5080 / 0x508C, all three carrying the
    same destination 0x02D7 with different file/frame pairs.

The disc file NAMES come from the disc's own file list
(`~/ddw3/iso/dw2003-bootstrap/lbas.toml`), never from a hand-written table.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path.home() / "ddw3/asm/dw2003/pro/stdwtitl.s"
FILE_LIST = Path.home() / "ddw3/iso/dw2003-bootstrap/lbas.toml"
START = 0x4FE8
ROWS = 12
OUT = ROOT / "engine/dw3/movie-destinations.ts"


def table_words():
    words = {}
    for line in SOURCE.read_text().splitlines():
        match = re.match(r"\.L0x([0-9a-fA-F]+): \.word 0x([0-9a-fA-F]+)", line)
        if match:
            offset = int(match[1], 16)
            if START <= offset < START + ROWS * 12:
                words[offset] = int(match[2], 16)
    if len(words) != ROWS * 3:
        raise ValueError("movie table is incomplete")
    return words


def disc_file_names():
    names = [n for n in re.findall(r'"([^"]+)"', FILE_LIST.read_text()) if n != "lbas"]
    return names


def rows():
    words = table_words()
    names = disc_file_names()
    out = []
    for index in range(ROWS):
        base = START + index * 12
        file_index = words[base]
        frames = words[base + 4]
        destination = words[base + 8]
        name = names[file_index] if 0 <= file_index < len(names) else None
        if name is None:
            raise ValueError(f"movie {index}: disc file index {file_index} is not in the file list")
        out.append({
            "index": index,
            "fileIndex": file_index,
            "file": name,
            "frames": frames,
            "destination": destination,
            "label": f".L0x{base:08x}",
        })
    return out


# `F0x80083CC0`: the ordinal-45 override on movie 2's return selector.
POST_GAME_MOVIE_INDEX = 2
POST_GAME_DESTINATION = 0x276


if __name__ == "__main__":
    table = rows()
    lines = [
        "// Generated by tools/extract_movie_destinations.py; authored disc data.",
        "// pro/stdwtitl.s .L0x00004fe8-.L0x00005074, twelve 12-byte rows read by",
        "// F0x80083CC0 as {disc file index, frame count, return selector}.",
        "",
        "export interface MovieRow {",
        "  /** Index into this table; the launch code's low byte minus one (F0x80083f48). */",
        "  index: number;",
        "  /** The disc file the movie object loads (`LoadFile(index, 0, &obj->+0x50)`). */",
        "  fileIndex: number;",
        "  /** The disc's own filename for that file. */",
        "  file: string;",
        "  /** Frames the movie object counts before it ends (row+4). */",
        "  frames: number;",
        "  /** Selector launched when the movie ends (row+8); high byte = overlay library. */",
        "  destination: number;",
        "  /** The overlay label the row was read from. */",
        "  label: string;",
        "}",
        "",
        "export const MOVIE_ROWS: readonly MovieRow[] = [",
    ]
    for r in table:
        lines.append(
            f"  {{ index: {r['index']}, fileIndex: {r['fileIndex']}, "
            f"file: {r['file']!r}, frames: {r['frames']}, "
            f"destination: 0x{r['destination']:x}, label: {r['label']!r} }},"
        )
    lines += [
        "];",
        "",
        "/** Movie 2's return selector at master ordinal 0x2d (45) instead of its own. */",
        f"export const MOVIE_POST_GAME_INDEX = {POST_GAME_MOVIE_INDEX};",
        f"export const MOVIE_POST_GAME_DESTINATION = 0x{POST_GAME_DESTINATION:x};",
        "",
        "export const MOVIE_DESTINATIONS: readonly number[] = MOVIE_ROWS.map(",
        "  (row) => row.destination,",
        ");",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"Copied {len(table)} movie rows to {OUT.relative_to(ROOT)}")
