// engine/dw3/random-stream.ts
// THE GAME'S ONE RANDOM STREAM.
//
// The disc has exactly one random source in its own code: the table walk at
// `rand_u16` (exe/fns.s:10116-10134), reached through the FUNCTION POINTER the
// service block at 0x8004DC00 holds. It is not a generator, not an LCG and not
// hardware noise -- it walks a 4096-halfword table the disc ships, off a single
// index word:
//
//     RAND_TABLE_CUR_IDX = (RAND_TABLE_CUR_IDX + 1) & 0xfff ;
//     return RAND_TABLE[RAND_TABLE_CUR_IDX] ;          // `lhu`, so 0..0x0fff
//
// The two cell addresses and the table's own address are the service block's
// three words (exe data image, data.rs:3690 and :3950-3952):
//
//     0x8004bc04   RAND_TABLE            4096 halfwords, extracted verbatim
//     0x8004dc04   RAND_TABLE_CUR_IDX    the index word; the data image value is 0
//     0x8004dc08   RAND_U16_SET_SEED     stores `seed & 0xfff` into the index
//     0x8004dc0c   RAND_U16              the generator, called through this cell
//
// ONE stream, not one per system. A census of every reference to 0x8004dc0c
// across all 318 disassembled overlays and the EXE (a lui/addiu constant walk per
// register, because an overlay has no link-time symbol for it) finds 87 call
// sites in 12 overlays and NOTHING anywhere else: the battle overlay, the field
// overlays, the card duel, the title, the gym, the fight report, the shop and the
// pause screen all read the SAME word. See RAND_STREAM.consumers for the list and
// docs/research/battle/game-random-stream-2026-10-05.md for the per-file rows.
//
// `rand_u16_set_seed` has NO caller in the whole corpus and the index word's data
// image is 0, so a cold boot takes table index 1 on the first call and the stream
// runs one long cycle of 4096 values until it wraps. The seeder is kept because it
// is the disc's own routine and a savestate-loaded game can carry a seeded index.
//
// WHY THE WALKER HAD ITS OWN: every battle roll went through `RAND_U16`, which was
// `(Math.random() * 0x10000) | 0` -- the right RANGE and a different source, so the
// idle camera's shot walk, the stage-object heading and the damage rolls each drew
// from their own sequence instead of sharing one. They now share this one.
//
// The table is stored as one hex string rather than 4096 array entries so the
// bundled `web/vendor/engine.js` stays small; `tests/random-stream.test.js` checks
// it against the extracted `web/assets/native/exe_tables.json`, which
// tools/build_native_overlays.py regenerates from the EXE data image.

