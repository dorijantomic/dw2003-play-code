function decodeTable(hex: string): Uint16Array {
  const out = new Uint16Array(hex.length / 4);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(hex.substr(i * 4, 4), 16);
  return out;
}

/** The table, decoded once. Read-only to callers; the stream only reads it. */
export const DISC_RAND_TABLE: Uint16Array = decodeTable(TABLE_HEX);

/**
 * Everything about the stream that is the disc's own, as one table, so a test can
 * hold the code's member list against the decoded list.
 *
 * `consumers` is the CENSUS: every overlay that calls [0x8004dc0c], with the number
 * of call sites each one has. It is the whole population -- there is no thirteenth
 * overlay, and the EXE itself never calls the stream (it only publishes the pointer).
 */
export const RAND_STREAM = Object.freeze({
  /** 0x8004bc04: the 4096-halfword table the generator walks. */
  tableBase: 0x8004bc04,
  /** 0x8004dc04: the index word. The data image's value is 0. */
  indexCell: 0x8004dc04,
  /** 0x8004dc08: `rand_u16_set_seed` -- stores `seed & 0xfff` into the index. */
  setSeedCell: 0x8004dc08,
  /** 0x8004dc0c: `rand_u16` -- the generator, reached through this cell. */
  valueCell: 0x8004dc0C,
  /** 4096 entries, indexed `& 0xfff`, so the cycle is 4096 calls long. */
  tableSize: 0x1000,
  /** The generator's own comment: a value from 0 up to (not including) 0x1000. */
  valueRange: 0x1000,
  /** The data image's index value, and so the first table index a cold boot reaches. */
  bootIndex: 0,
  /** `rand_u16` in the EXE. */
  valueRoutine: 0x8001933c,
  /** `rand_u16_set_seed` in the EXE. */
  setSeedRoutine: 0x8001932c,
  /** The overlays that call the stream, and how many call sites each has. */
  consumers: Object.freeze([
    Object.freeze({ overlay: "CARDGAME", file: "pro/cardgame.s", refs: 4 }),
    Object.freeze({ overlay: "FIELDSTG", file: "pro/fieldstg.s", refs: 8 }),
    Object.freeze({ overlay: "FIGHTSTG", file: "pro/fightstg.s", refs: 45 }),
    Object.freeze({ overlay: "STCRDSHP", file: "pro/stcrdshp.s", refs: 1 }),
    Object.freeze({ overlay: "STDWTITL", file: "pro/stdwtitl.s", refs: 4 }),
    Object.freeze({ overlay: "STFGTREP", file: "pro/stfgtrep.s", refs: 4 }),
    Object.freeze({ overlay: "STGTRAIN", file: "pro/stgtrain.s", refs: 6 }),
    Object.freeze({ overlay: "STSTATUS", file: "pro/ststatus.s", refs: 1 }),
    Object.freeze({ overlay: "WFIGHTMN", file: "pro/wfightmn.s", refs: 4 }),
    Object.freeze({ overlay: "WSTAG460", file: "pro/wstag460.s", refs: 3 }),
    Object.freeze({ overlay: "WSTAG526", file: "pro/wstag526.s", refs: 3 }),
    Object.freeze({ overlay: "WSTAG780", file: "pro/wstag780.s", refs: 4 }),
  ]),
});

/** The index word, the stream's whole state. The data image's value is 0. */
let index: number = RAND_STREAM.bootIndex;

/**
 * `rand_u16` (F0x8001933c): advance the index past the wrap, store it, and hand
 * back the table word under it. One call, one advance, 0x1000 calls to a cycle.
 */
export function randU16(): number {
  index = (index + 1) & 0xfff;
  return DISC_RAND_TABLE[index] as number;
}

/**
 * `rand_u16_set_seed` (F0x8001932c): store `seed & 0xfff`. The NEXT call still
 * advances first, so a seeded stream returns the word AFTER the seeded index, never
 * the seeded index itself. The disc ships no caller; kept because it is the routine
 * at 0x8004dc08 and a seeded game can arrive with the index already set.
 */
export function randU16SetSeed(seed: number): void {
  index = (seed | 0) & 0xfff;
}

/** The index word, for a test that re-derives the advance rule. */
export function randU16Index(): number {
  return index;
}
