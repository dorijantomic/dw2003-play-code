def build_wstag_events():
    out = OUT / "events/wstag_events.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    result = subprocess.run(
        [sys.executable, str(Path(__file__).parent / "tools/wstag_events.py"),
         "--all", "--output", str(out)],
        capture_output=True, text=True
    )
    if result.returncode != 0:
        print("wstag_events error:", result.stderr)
    else:
        print(result.stderr.strip())


def main():
    (OUT / "sprites").mkdir(parents=True, exist_ok=True)
    (OUT / "maps").mkdir(parents=True, exist_ok=True)

    copy_findings()
    copy_screen_table()
    build_wstag_events()

    maps = []
    skipped = []
    for m in MAPS:
        try:
            maps.append(build_map(m))
        except Exception as e:
            skipped.append(m['id'])
            print(f"  ! {m['id']} skipped: {e}")
    manifest = {
        "characters": [build_sheet(c, CHAR_ROW_ORDER) for c in CHARACTERS],
        "maps": maps,
        "npcs": [build_sheet(c, NPC_ROW_ORDER) for c in NPCS],
    }
    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=1))
    print(f"Built {len(manifest['characters'])} characters, {len(manifest['maps'])} maps, {len(manifest['npcs'])} npcs")
    if skipped:  # a missing map is a broken stage, not a warning
        sys.exit(f"{len(skipped)} of {len(MAPS)} maps failed to build: {', '.join(skipped[:10])}"
                 + (" ..." if len(skipped) > 10 else ""))


if __name__ == "__main__":
    main()
