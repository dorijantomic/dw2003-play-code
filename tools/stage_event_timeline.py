#!/usr/bin/env python3
"""Static event timelines per stage: gate -> script -> hook -> flags/handoff.

The browser call journal measures the stage's own actor code but cannot drive the
resident story layer, so the events each stage fires live here: every event in
`web/assets/events/wstag_events.json` with its gate from
`web/assets/data/auto_event_gates.json`, its decoded script disassembly, the
recovered names of its native handler and on-complete hook, and its text/handoff
destination.

    python3 tools/stage_event_timeline.py                 # summary
    python3 tools/stage_event_timeline.py --write docs/generated/stage-event-timelines.md
    python3 tools/stage_event_timeline.py --stage 310     # one stage
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from crosscheck_stage_journal import stage_starts  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent


def gate_ordinal(conds: list[list[int]]) -> int | None:
    ordinal = None
    for flag, expected in conds:
        if 0x6000 <= flag <= 0x60FF and expected == 1:
            ordinal = flag - 0x6000
    return ordinal


def script_frames(disasm: list[str]) -> int:
    total = 0
    for op in disasm:
        if op.startswith("WAIT "):
            try:
                total += int(op.split()[1])
            except (IndexError, ValueError):
                pass
    return total


def event_rows(stage: int) -> list[dict]:
    events = json.loads((ROOT / "web/assets/events/wstag_events.json").read_text())
    gates = json.loads((ROOT / "web/assets/data/auto_event_gates.json").read_text())
    names = stage_starts(stage)
    gate_map = gates.get(f"s{stage}") or {}
    rows = []
    for e in events.get(f"s{stage}", []):
        gate = gate_map.get(str(e["id"]))
        conds = gate["conds"] if gate else []
        rows.append({
            "event": e["id"],
            "ordinal": gate_ordinal(conds) if conds else None,
            "gate_flags": [f"0x{c[0]:04x}=={c[1]}" for c in conds if not (0x6000 <= c[0] <= 0x60FF)],
            "script_offset": e.get("script_offset"),
            "script_frames": script_frames(e.get("disasm") or []),
            "steps": e.get("disasm") or [],
            "native": names.get(e.get("native_fn_ram") or 0),
            "native_addr": f"0x{e['native_fn_ram']:08x}" if e.get("native_fn_ram") else None,
            "on_complete": names.get(e.get("on_complete_fn_ram") or 0),
            "on_complete_addr": f"0x{e['on_complete_fn_ram']:08x}" if e.get("on_complete_fn_ram") else None,
            "text": f"esdmg {e['esdmg_stage']}:{e['esdmg_entry']}" if e.get("esdmg_stage") else None,
            "handoff": (e["handoff_to"] if str(e["handoff_to"]).startswith("s") else f"s{e['handoff_to']}")
            if e.get("handoff_to") else None,
        })
    rows.sort(key=lambda r: (r["ordinal"] is None, r["ordinal"] or 0, r["event"]))
    return rows


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage", type=int)
    ap.add_argument("--write", type=pathlib.Path)
    ap.add_argument("--json", type=pathlib.Path)
    args = ap.parse_args()

    events = json.loads((ROOT / "web/assets/events/wstag_events.json").read_text())
    stages = [args.stage] if args.stage else sorted(int(s[1:]) for s in events)

    all_rows = {f"s{s}": event_rows(s) for s in stages}

    if args.json:
        args.json.write_text(json.dumps(all_rows, indent=1) + "\n")
        print(f"wrote {args.json}")

    if args.write:
        lines = [
            "---",
            "reach: Reading which story events a stage fires, when, what each script does and which recovered hook it runs — the static half of a stage's call timeline.",
            "status: generated",
            "---",
            "",
            "# Stage event timelines — gate, script, hook",
            "",
            "> Generated by `python3 tools/stage_event_timeline.py --write docs/generated/stage-event-timelines.md`.",
            "> Do not edit by hand; fix the generator.",
            "",
            "One row per event. `ordinal` is the story beat its gate needs; `gate flags` are the",
            "other conditions (must be set as shown). `script frames` counts only `WAIT n`; `WAITCTX`",
            "(dialogue open) and `SAY` add time a player controls. `hook` is the recovered function",
            "that runs when the script completes. This is table data, not an observation.",
            "",
        ]
        for stage, rows in all_rows.items():
            lines.append(f"## {stage} — {len(rows)} events")
            lines.append("")
            if not rows:
                lines.append("No event records.")
                lines.append("")
                continue
            lines.append("| event | ordinal | gate flags | script frames | steps | native | on-complete hook | text | handoff |")
            lines.append("|---:|---:|---|---:|---:|---|---|---|---|")
            for r in rows:
                steps = " ".join(r["steps"])
                if len(steps) > 90:
                    steps = steps[:80] + "…"
                lines.append(
                    f"| {r['event']} | {r['ordinal'] if r['ordinal'] is not None else '—'} "
                    f"| {', '.join(r['gate_flags']) or '—'} | {r['script_frames']} | `{steps}` "
                    f"| {r['native'] or '—'} | {r['on_complete'] or '—'} | {r['text'] or '—'} "
                    f"| {r['handoff'] or '—'} |"
                )
            lines.append("")
        args.write.write_text("\n".join(lines) + "\n")
        print(f"wrote {args.write}")

    if not args.write and not args.json:
        total = sum(len(r) for r in all_rows.values())
        with_ordinal = sum(1 for r in all_rows.values() for x in r if x["ordinal"] is not None)
        with_hook = sum(1 for r in all_rows.values() for x in r if x["on_complete"])
        print(f"{len(all_rows)} stages, {total} events, {with_ordinal} ordinal-gated, {with_hook} with on-complete hook")
    return 0


if __name__ == "__main__":
    sys.exit(main())
