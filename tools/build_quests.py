#!/usr/bin/env python3
"""Build web/quests.json from its sources: data/authored/quests/legacy.json plus every pack_*.py (docs/quests-bible.md),
and data/authored/quests/triggers.json (the walk-in quest triggers, web/quest-triggers.js).

    python3 tools/build_quests.py            writes web/quests.json and prints what it holds
    python3 tools/build_quests.py --check    builds in memory and fails if web/quests.json is out of date
    python3 tools/build_quests.py --out <file>   write somewhere else (a test build; web/quests.json is untouched)
    python3 tools/build_quests.py --with-drafts   local testing only: also put every draft (not in shipped.txt) in
                                             web/quests.json so the quest lab can play it; run without it before committing

Do not edit web/quests.json by hand. Quest ids are append-only: progress is stored by id.
"""
import collections
import importlib
import json
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "data", "authored", "quests")
OUT = os.path.join(ROOT, "web", "quests.json")
sys.path.insert(0, SRC)

COMMENT = ("Extra quests (new content, not part of the shipped game). GENERATED by tools/build_quests.py from "
           "data/authored/quests/ - edit the sources, not this file. Stage lists name BOTH worlds where a place exists as a "
           "normal and a post-game version. See docs/quests-bible.md.")

TRIGGERS = os.path.join(SRC, "triggers.json")
TRIGGER_STATUSES = {"available", "active", "ready", "done"}
# the game's own text format: letters, digits and . , ' - : " ! ?
TEXT_OK = re.compile(r"^[A-Za-z0-9 .,'\-:\"!?]*$")


def trigger_problems(triggers):
    """Everything wrong with the authored triggers' shape (the maps, the ground and the scenes are
    tools/check_triggers.mjs's business: it reads the game's own collision and scene data)."""
    problems, ids = [], set()
    for i, t in enumerate(triggers):
        where = f"trigger {i + 1}"
        if not isinstance(t, dict):
            problems.append(f"{where} is not an object")
            continue
        tid = t.get("id")
        if not isinstance(tid, str) or not tid:
            problems.append(f"{where} needs an id (the fired mark is kept by it)")
        else:
            where = f"trigger {tid}"
            if tid in ids:
                problems.append(f"{where}: duplicate id")
            ids.add(tid)
        if not isinstance(t.get("map"), str) or not t["map"]:
            problems.append(f"{where} needs a map")
        rect = t.get("rect")
        if not (isinstance(rect, list) and len(rect) == 4
                and all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in rect)):
            problems.append(f"{where}: rect must be [x, y, width, height] in whole pixels")
        elif rect[2] <= 0 or rect[3] <= 0:
            problems.append(f"{where}: rect needs a positive width and height")
        if "once" in t and not isinstance(t["once"], bool):
            problems.append(f"{where}: once must be true or false")
        if "draft" in t and not isinstance(t["draft"], bool):
            problems.append(f"{where}: draft must be true or false")
        when = t.get("when")
        if when is not None:
            if not isinstance(when, dict) or not isinstance(when.get("quest"), str) or not when["quest"]:
                problems.append(f"{where}: when needs a quest id")
            elif when.get("status") not in TRIGGER_STATUSES:
                problems.append(f"{where}: when.status must be one of {', '.join(sorted(TRIGGER_STATUSES))}")
        scene = t.get("scene")
        if not (isinstance(scene, list) and scene):
            problems.append(f"{where} has no scene")
            continue
        for j, step in enumerate(scene):
            if not isinstance(step, dict):
                problems.append(f"{where}: scene step {j + 1} is not an object")
                continue
            text = step.get("text")
            if isinstance(text, str) and not TEXT_OK.match(text):
                bad = sorted(set(re.sub(r"[A-Za-z0-9 .,'\-:\"!?]", "", text)))
                problems.append(f"{where}: scene step {j + 1} text has characters the game text cannot show: {bad}")
    return problems


def main():
    import dsl
    legacy = json.load(open(os.path.join(SRC, "legacy.json"), encoding="utf-8"))["quests"]
    packs = sorted(f[:-3] for f in os.listdir(SRC) if f.startswith("pack_") and f.endswith(".py"))
    quests, where = list(legacy), {q["id"]: "legacy" for q in legacy}
    per_pack = collections.OrderedDict([("legacy", len(legacy))])
    try:
        for name in packs:
            mod = importlib.import_module(name)
            for q in mod.QUESTS:
                if q["id"] in where:
                    raise dsl.BuildError(f"duplicate quest id {q['id']!r} (in {name} and {where[q['id']]})")
                where[q["id"]] = name
                quests.append(q)
            per_pack[name] = len(mod.QUESTS)
    except dsl.BuildError as e:
        print("BUILD ERROR:", e)
        return 1
    if dsl.PROBLEMS:
        print(f"{len(dsl.PROBLEMS)} problem(s) in the packs:")
        for p in dsl.PROBLEMS:
            print("  -", p)
        return 1
    shipped = {l.strip() for l in open(os.path.join(SRC, "shipped.txt"), encoding="utf-8") if l.strip() and not l.startswith("#")}
    drafts = [q["id"] for q in quests if where[q["id"]] != "legacy" and q["id"] not in shipped]
    if "--with-drafts" in sys.argv:
        drafts = []
    quests = [q for q in quests if q["id"] not in set(drafts)]
    for q in quests:                      # a shipped quest never waits on a draft
        u = q.get("unlock") or {}
        if u.get("done") in drafts:
            del u["done"]
        r = q.get("requires") or {}
        if r.get("done") in drafts:
            del r["done"]
            if not r:
                del q["requires"]
    # props (our own art a quest's state leaves on a map, web/quest-props.js): they travel with the quest data as they
    # were authored, with the one default filled in so the runtime and the JSON always agree on what "after" means.
    for q in quests:
        for p in q.get("props") or []:
            if isinstance(p, dict):
                p.setdefault("after", "done")
    # walk-in quest triggers (web/quest-triggers.js): authored in triggers.json, checked for shape here; the maps, the
    # ground and the scenes are tools/check_triggers.mjs's job. A draft trigger ships only with --with-drafts, exactly
    # like a draft quest, so it can be tried in the lab without appearing in the game.
    triggers = []
    if os.path.exists(TRIGGERS):
        triggers = json.load(open(TRIGGERS, encoding="utf-8")).get("triggers") or []
    bad = trigger_problems(triggers)
    if bad:
        print(f"{len(bad)} problem(s) in the triggers:")
        for b in bad:
            print("  -", b)
        return 1
    built_triggers = [t for t in triggers if "--with-drafts" in sys.argv or not t.get("draft")]
    out = OUT
    if "--out" in sys.argv:
        i = sys.argv.index("--out")
        if i + 1 >= len(sys.argv):
            print("--out needs a file to write")
            return 1
        out = os.path.abspath(sys.argv[i + 1])
    text = json.dumps({"_comment": COMMENT, "quests": quests, "triggers": built_triggers}, indent=2, ensure_ascii=False)
    if "--check" in sys.argv:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("web/quests.json is up to date" if ok else "web/quests.json is OUT OF DATE: run tools/build_quests.py")
        return 0 if ok else 1
    open(out, "w", encoding="utf-8").write(text)
    kinds = collections.Counter(o["type"] for q in quests for o in q["objectives"])
    scenes = sum(1 for q in quests if q.get("offer", {}).get("scene"))
    print(f"wrote {out}: {len(quests)} quests ({', '.join(f'{k} {v}' for k, v in per_pack.items())})")
    print("objectives:", ", ".join(f"{k} {v}" for k, v in sorted(kinds.items())))
    print(f"{scenes} quests have a walking offer scene; {sum(1 for q in quests if q.get('reward', {}).get('items'))} give an item")
    print(f"{len(built_triggers)} walk-in trigger(s)" + (f" ({len(triggers) - len(built_triggers)} draft left out)" if len(built_triggers) != len(triggers) else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
