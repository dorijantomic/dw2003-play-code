"""Reviewable, reversible application of results into semantics.json.

Only **mechanically established** results are ever written automatically. A
heuristic name -- however often its rule happens to be right across the corpus
-- stays a candidate in `semantic-candidates.json` and never enters the curated
file, because a classifier's aggregate precision is not evidence about the one
function in front of it.

Every written entry is marked `generated: true` with the tool, rule version and
evidence paths that produced it, so the whole set can be listed, regenerated or
removed without touching a single hand-curated annotation.
"""

from __future__ import annotations

import json
from pathlib import Path

from . import RULE_VERSION

GENERATED_MARKER = "generated"
TOOL = "tools/infer_recovered_semantics.py"


def eligible(candidate) -> bool:
    """Auto-apply gate. Deliberately narrow."""
    if candidate["name_basis"] == "curated" or not candidate["proposed_name"]:
        return False
    if not candidate["mechanically_established"]:
        return False
    if candidate["contradictions"]:
        return False
    if candidate["lift"] != "decompiled_c_complete":
        return False
    # A name resting on one clue with nothing corroborating it is exactly the
    # weak-single-clue case; it belongs in review, not in the curated file.
    if len(candidate["evidence"]) < 2 and candidate["name_basis"] != "mechanical_role":
        return False
    return True


def _semantics_status(candidate) -> str:
    """Exact homology with a curated origin is strong; a rule match is not."""
    if candidate["name_basis"] == "propagated_curated" and candidate["provenance"]["hops"] == 1:
        return "strongly_inferred"
    return "candidate"


def build_entry(candidate) -> dict:
    return {
        "name": candidate["proposed_name"],
        "subsystem": candidate.get("subsystem") or "unclassified",
        "signature": candidate["signature"],
        "summary": candidate["summary"],
        "structure_fields": candidate["structure_fields"],
        "recovery": {
            "lift": "decompiled_c_present",
            "structure": "partial" if candidate["structure_fields"] else "unknown",
            "semantics": _semantics_status(candidate),
            # Never `verified`. Promotion is a separate, gated, human step.
            "verification": "candidate",
            "implementation": "unknown",
        },
        "evidence": candidate["evidence"][:12],
        "unknowns": candidate["unknowns"] or [
            "generated by mechanical inference; not reviewed against original assembly",
        ],
        GENERATED_MARKER: True,
        "generated_by": TOOL,
        "rule_version": RULE_VERSION,
        "evidence_paths": candidate["evidence_paths"],
        "provenance_path": candidate["provenance"]["path"],
    }


def coverage(semantics: dict, corpus) -> dict:
    functions = semantics.get("functions", {})
    family_members = {
        fid for family in semantics.get("families", {}).values()
        for fid in family.get("members", {})
    }
    named = set(functions) | family_members
    generated = {fid for fid, entry in functions.items() if entry.get(GENERATED_MARKER)}
    return {
        "total_functions": len(corpus.functions),
        "named": len(named & set(corpus.functions)),
        "curated": len((named - generated) & set(corpus.functions)),
        "generated": len(generated & set(corpus.functions)),
        "unnamed": len(set(corpus.functions) - named),
    }


def apply(semantics_path: Path, candidates: dict, corpus, *, batch_size: int = 50,
          limit: int | None = None, dry_run: bool = False) -> dict:
    semantics = json.loads(semantics_path.read_text())
    functions = semantics.setdefault("functions", {})
    curated_ids = corpus.curated_ids()

    before = coverage(semantics, corpus)
    pending = [
        candidate for fid, candidate in sorted(candidates.items())
        if eligible(candidate)
        and fid not in curated_ids
        and not (fid in functions and not functions[fid].get(GENERATED_MARKER))
    ]
    if limit is not None:
        pending = pending[:limit]

    batches = []
    for start in range(0, len(pending), batch_size):
        chunk = pending[start:start + batch_size]
        for candidate in chunk:
            functions[candidate["id"]] = build_entry(candidate)
        batches.append({
            "batch": len(batches) + 1,
            "applied": len(chunk),
            "ids": [candidate["id"] for candidate in chunk],
            "coverage_after": coverage(semantics, corpus),
            "name_bases": sorted({candidate["name_basis"] for candidate in chunk}),
        })

    after = coverage(semantics, corpus)
    if not dry_run and pending:
        semantics["functions"] = dict(sorted(functions.items()))
        semantics_path.write_text(json.dumps(semantics, indent=2) + "\n")

    return {
        "dry_run": dry_run,
        "eligible": len(pending),
        "skipped_not_mechanical": sum(
            1 for c in candidates.values()
            if c["proposed_name"] and not c["mechanically_established"]
            and c["name_basis"] != "curated"
        ),
        "batch_size": batch_size,
        "batches": batches,
        "coverage_before": before,
        "coverage_after": after,
    }


def revert(semantics_path: Path) -> dict:
    """Remove every generated entry, leaving curated annotations untouched."""
    semantics = json.loads(semantics_path.read_text())
    functions = semantics.get("functions", {})
    removed = [fid for fid, entry in functions.items() if entry.get(GENERATED_MARKER)]
    for fid in removed:
        del functions[fid]
    semantics_path.write_text(json.dumps(semantics, indent=2) + "\n")
    return {"removed": len(removed), "ids": removed}
