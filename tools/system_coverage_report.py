#!/usr/bin/env python3
"""Generate docs/generated/system-coverage.md: every system's knowledge and
implementation status in one page.

Reads only two files, so it can run while the research index lock is held:
  docs/research/systems/catalog.json  (navigation + coverage + implementation)
  docs/research/evidence/ledger.json  (ground-truth claim statuses)

The distinction the report must preserve: a ledger claim status is knowledge
about the original game; `implementation_status` is what the browser walker
ships; `coverage.exhaustive` is the only statement that a system's scope has
been fully enumerated. They are three separate axes and none implies another.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "docs/research/systems/catalog.json"
LEDGER = ROOT / "docs/research/evidence/ledger.json"
OUT = ROOT / "docs/generated/system-coverage.md"

STATUS_ORDER = ["verified", "partially_verified", "candidate", "unresearched", "contradicted"]
OPEN_FRONTIER = ("open", "needs_evidence")


def load():
    catalog = json.loads(CATALOG.read_text())
    ledger = json.loads(LEDGER.read_text())
    return catalog, ledger


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--json", action="store_true", help="emit the tally instead of the markdown")
    args = ap.parse_args()

    catalog, ledger = load()
    systems = catalog["systems"]
    claims = ledger["claims"]

    by_system: dict[str, list] = {}
    for c in claims:
        by_system.setdefault(c.get("system") or "(none)", []).append(c)

    rows = []
    for s in systems:
        name = s["system"]
        sc = by_system.get(name, [])
        counts = {st: sum(1 for c in sc if c.get("status") == st) for st in STATUS_ORDER}
        fronts = s.get("frontiers", []) or []
        open_fronts = [f for f in fronts if f.get("status") in OPEN_FRONTIER]
        impl = s.get("implementation") or {}
        rows.append({
            "system": name,
            "aliases": s.get("aliases", []),
            "catalog_status": s.get("status"),
            "summary": s.get("summary", "").strip(),
            "claims": counts,
            "claims_total": len(sc),
            "contradicted_ids": sorted(c["id"] for c in sc if c.get("status") == "contradicted"),
            "frontiers": fronts,
            "open_frontiers": open_fronts,
            "exhaustive": bool((s.get("coverage") or {}).get("exhaustive")),
            "scope": ((s.get("coverage") or {}).get("scope") or "").strip(),
            "implementation_status": s.get("implementation_status"),
            "modules": impl.get("modules", []),
            "tests": impl.get("tests", []),
            "impl_verified": impl.get("verified"),
            "impl_note": (impl.get("note") or s.get("implementation_note") or "").strip(),
            "canonical_docs": s.get("canonical_docs", []),
        })
    rows.sort(key=lambda r: r["system"])

    if args.json:
        print(json.dumps(rows, indent=1))
        return 0

    totals = {st: sum(r["claims"][st] for r in rows) for st in STATUS_ORDER}
    total_claims = sum(totals.values())
    frontier_counts = {k: sum(1 for r in rows for f in r["frontiers"] if f.get("status") == k)
                       for k in ("resolved", "needs_evidence", "open")}
    impl_counts = {}
    for r in rows:
        impl_counts[r["implementation_status"]] = impl_counts.get(r["implementation_status"], 0) + 1
    exhaustive_true = [r["system"] for r in rows if r["exhaustive"]]
    with_open = [r["system"] for r in rows if r["open_frontiers"]]

    L = []
    L.append("---")
    L.append("reach: Asking how much of a game system is known from the original code "
             "(verified vs candidate), which systems still have open questions, which are "
             "covered exhaustively, and what the walker implements. Read before quoting a "
             "system as done or picking the next decode target.")
    L.append("status: generated")
    L.append("---")
    L.append("")
    L.append("# Every system: how much we know, how much is implemented")
    L.append("")
    L.append("Generated by `tools/system_coverage_report.py` from "
             "`docs/research/systems/catalog.json` and `docs/research/evidence/ledger.json`. "
             "Do not edit by hand; regenerate instead. The browsable page with translation, checks and gaps is `web/systems.html`. The catalog's own note: it is "
             "*navigation and coverage metadata only* — ground-truth claims live in the ledger.")
    L.append("")
    L.append("Three separate axes, none implying another:")
    L.append("")
    L.append("- **Knowledge** — the ledger claim status. `verified` is the only status that may "
             "be presented as original-game ground truth; `partially_verified` and `candidate` "
             "are unproven; `contradicted` rows are readings the game or a later pass disproved.")
    L.append("- **Coverage** — `coverage.exhaustive` is the only flag saying a system's stated "
             "scope has been fully enumerated. All other counts are breadth, not coverage.")
    L.append("- **Implementation** — `implementation_status` is what the browser walker ships, "
             "checked by `tools/check_implementation_status.py`. It is not evidence about the "
             "original game.")
    L.append("")
    L.append(f"- Systems: **{len(rows)}**")
    L.append(f"- Ledger claims: **{total_claims}** — "
             + ", ".join(f"{st} {totals[st]}" for st in STATUS_ORDER))
    L.append(f"- Catalogued frontiers: **{sum(frontier_counts.values())}** — "
             f"resolved {frontier_counts['resolved']}, "
             f"needs_evidence {frontier_counts['needs_evidence']}, "
             f"open {frontier_counts['open']}")
    L.append(f"- Systems with a non-exhaustive scope: **{len(rows) - len(exhaustive_true)} of "
             f"{len(rows)}** (exhaustive so far: {', '.join(exhaustive_true) if exhaustive_true else 'none'})")
    L.append(f"- Systems with open questions: **{len(with_open)} of {len(rows)}** "
             f"({', '.join(with_open)})")
    L.append("- Implementation status: "
             + ", ".join(f"{k} {v}" for k, v in sorted(impl_counts.items())))
    L.append("")
    L.append("The mechanical finish line is `./dw3-research completion-check`; it fails on every "
             "non-exhaustive system and every unresolved frontier. This page is a snapshot of "
             "the inputs to that check, not a substitute for it.")
    L.append("")
    L.append("## Verified-claim breadth by system (not coverage)")
    L.append("")
    L.append("A high share here means many readings were promoted through review. It says nothing "
             "about the fraction of the system that has been read.")
    L.append("")
    L.append("| system | verified | partial | candidate | contradicted | claims |")
    L.append("|---|---:|---:|---:|---:|---:|")
    for r in sorted(rows, key=lambda r: (-r["claims"]["verified"], r["system"])):
        c = r["claims"]
        L.append(f"| {r['system']} | {c['verified']} | {c['partially_verified']} | "
                 f"{c['candidate']} | {c['contradicted']} | {r['claims_total']} |")
    L.append("")

    for r in rows:
        c = r["claims"]
        L.append(f"## {r['system']}")
        if r["aliases"]:
            L.append("")
            L.append(f"*aliases:* {', '.join(r['aliases'])}")
        L.append("")
        L.append(f"- **Knowledge status (catalog):** `{r['catalog_status']}` — {r['summary']}")
        L.append(f"- **Ledger claims:** {r['claims_total']} — verified {c['verified']}, "
                 f"partially_verified {c['partially_verified']}, candidate {c['candidate']}, "
                 f"unresearched {c['unresearched']}, contradicted {c['contradicted']}")
        if r["contradicted_ids"]:
            L.append("- **Contradicted claim ids:** " + ", ".join(r["contradicted_ids"]))
        L.append(f"- **Coverage:** exhaustive = **{str(r['exhaustive']).lower()}** — "
                 f"scope: {r['scope'] or '(none stated)'}")
        if r["frontiers"]:
            unresolved = [f for f in r["frontiers"] if f.get("status") in OPEN_FRONTIER]
            resolved = [f for f in r["frontiers"] if f.get("status") == "resolved"]
            L.append(f"- **Frontiers:** {len(resolved)} resolved, {len(unresolved)} unresolved")
            for f in unresolved:
                L.append(f"  - `{f.get('id')}` [{f.get('status')}] {f.get('question', '').strip()}")
        else:
            L.append("- **Frontiers:** none catalogued")
        isr = r["implementation_status"]
        mods = ", ".join(f"`{m}`" for m in r["modules"]) or "(none listed)"
        if isr == "not_applicable":
            L.append(f"- **Implementation:** `not_applicable`")
        else:
            tests = ", ".join(f"`{t}`" for t in r["tests"]) or "(none listed)"
            ver = f"; verified {r['impl_verified']}" if r["impl_verified"] else ""
            L.append(f"- **Implementation:** `{isr}` — modules: {mods}; tests: {tests}{ver}")
        if r["impl_note"]:
            L.append(f"- **Implementation note:** {r['impl_note']}")
        if r["canonical_docs"]:
            L.append("- **Canonical docs:** " + ", ".join(f"`{d}`" for d in r["canonical_docs"]))
        L.append("")
    L.append("## What this page does not say")
    L.append("")
    L.append("- It does not say any system is finished. Only a true `coverage.exhaustive` plus "
             "resolved frontiers closes a system, and `completion-check` is the judge.")
    L.append("- It does not prove original-game behavior. Only the ledger's `verified` status does, "
             "and the ledger is the citation target.")
    L.append("- It contains no wall-clock timestamp; regenerate after catalog, frontier or ledger "
             "changes.")
    L.append("")

    out = Path(args.out)
    out.write_text("\n".join(L))
    print(f"wrote {out} ({len(L)} lines, {out.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
