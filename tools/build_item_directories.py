#!/usr/bin/env python3
"""Generate engine/dw3/item-directories.ts — the five item-ID directories.

Source: the resident exe's directory pointer table at 0x80042BC8, five u32s
(nothing else reads them), and the halfword id lists they point at. That is the
table the routine F0x800135E8 walks to build EVERY item list in the game: the
pause ITEMS page's five tabs, the in-battle ITEM list (directory 1) and the
merchant SELL list (directory `cat` with a negative kind, so an item you have
equipped but hold none of is still listed).

Order in this file IS the order a player sees: the original returns the ids in
table order, never in the order the bag received them. Category contents read
this session:

    0  51 ids   1-42, 360, 395-402   key / story items
    1  83 ids   43-91, 361-394      consumables, disks/plugs, booster packs
    2 123 ids   92-214              weapons
    3  77 ids  215-291              the rest of the equipment band
    4  68 ids  292-359              accessories

51 + 83 + 123 + 77 + 68 = 402, so the five directories partition the whole item
space (ids 1..402) with nothing left over. There is no bound check in
F0x800135E8: an id outside those bands is simply never listed.

Ported routine: docs/research/items/item-store-shared-system-2026-10-03.md §3.
The engine/dw3/ui/shop-inventory.ts and engine/dw3/ui/native/pause-inventory.ts
ports of the walk read the same table out of the resident image in memory; this
module is the walker-side copy of the same ids, so a screen that never builds a
memory image can still list in the original's order.
"""

import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_native_screens import DEFAULT_DISC, load_exe  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "engine/dw3/item-directories.ts"
ITEM_DIRECTORY_TABLE = 0x80042BC8
DIRECTORY_COUNT = 5
MAX_IDS = 512


def read_directories(resident: bytes, base: int):
    rows = []
    for category in range(DIRECTORY_COUNT):
        pointer = struct.unpack_from("<I", resident, ITEM_DIRECTORY_TABLE + category * 4 - base)[0]
        start = pointer - base
        if start < 0 or start >= len(resident):
            raise ValueError(f"inventory category {category} points outside the resident image")
        ids = []
        for index in range(MAX_IDS):
            item = struct.unpack_from("<H", resident, start + index * 2)[0]
            if item == 0:
                break
            ids.append(item)
        else:
            raise ValueError(f"inventory category {category} lacks a terminator")
        rows.append(ids)
    return rows


def emit(rows) -> str:
    lines = [
        "// GENERATED by tools/build_item_directories.py from the disc's resident",
        "// image — do not edit. The pointer table at 0x80042BC8 and the halfword id",
        "// lists behind it, read by the original's F0x800135E8 (see the header of",
        "// tools/build_item_directories.py and",
        "// docs/research/items/item-store-shared-system-2026-10-03.md §3).",
        "",
        "/** How many id directories the original keeps; a kind outside 0..4 lists nothing. */",
        f"export const ITEM_DIRECTORY_COUNT = {DIRECTORY_COUNT};",
        "",
        "/** The highest item id any directory lists; ids 1..402 partition the five directories. */",
        f"export const ITEM_ID_MAX = {max(max(row) for row in rows)};",
        "",
        "/** Directory `kind`'s item ids in table order, or null when the kind is out of range. */",
        "export function itemDirectory(kind: number): readonly number[] | null {",
        "  const index = (kind | 0) & 0x7fffffff;",
        f"  return index < ITEM_DIRECTORY_COUNT ? ITEM_DIRECTORIES[index]! : null;",
        "}",
        "",
        "export const ITEM_DIRECTORIES: readonly (readonly number[])[] = [",
    ]
    for ids in rows:
        body = ", ".join(str(item) for item in ids)
        lines.append(f"  [{body}],")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    with DEFAULT_DISC.open("rb") as fh:
        base, resident = load_exe(fh)
    rows = read_directories(resident, base)
    flat = [item for row in rows for item in row]
    if sorted(flat) != list(range(1, len(flat) + 1)):
        raise SystemExit("the five directories do not partition ids 1..N")
    OUT.write_text(emit(rows))
    print(f"{OUT.relative_to(ROOT)}: {DIRECTORY_COUNT} directories, "
          f"{', '.join(str(len(row)) for row in rows)} ids, {len(flat)} total")


if __name__ == "__main__":
    main()