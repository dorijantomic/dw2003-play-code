#!/usr/bin/env python3
"""Write a reference sheet of the game world for people writing quests (docs/generated/quests-world.txt).

It answers, from the game's own data: which places exist (grouped by region, with their night/story variants), who stands
where (npc id, sprite, position), which enemies roam there (and which of those a `defeat` objective can name: single-enemy
roaming fights), what every fight screen holds (for `challenge` objectives), the item names a reward may use, and where
each place sits in the story. Read docs/quests-bible.md first; this file is the raw table behind it.

The output holds names and tables taken from the disc, so it is generated and git-ignored (docs/generated/quests-world.txt),
never committed. Needs web/assets (the built game data).

Usage: python3 tools/survey_world_for_quests.py
"""
import collections
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
WEB = os.path.join(ROOT, "web")
A = os.path.join(WEB, "assets")
D = os.path.join(A, "data")
load = lambda p: json.load(open(p, encoding="utf-8"))

manifest = load(os.path.join(A, "manifest.json"))
names = {m["id"]: m["name"] for m in manifest["maps"]}
variants = load(os.path.join(WEB, "map-variants.json"))          # variant map -> canonical map
stage_enc = load(os.path.join(D, "stage_encounters.json"))["stages"]
screens = load(os.path.join(D, "field_encounters.json"))["screens"]
chars_path = os.path.join(ROOT, "data", "authored", "quests", "characters.json")
persona = load(chars_path)["by_npc_id"] if os.path.exists(chars_path) else {}
item_names = load(os.path.join(D, "battlecmd", "esitmnam.json"))
if isinstance(item_names, dict):
    item_names = [v for v in item_names.values() if isinstance(v, str)] or [x for v in item_names.values() if isinstance(v, list) for x in v if isinstance(x, str)]

groups = collections.defaultdict(list)                           # canonical map -> [variants]
for v, c in variants.items():
    groups[c].append(v)
po = load(os.path.join(D, "progress_ordinal.json"))
story_order = {f"s{r['stage']}": r["ordinals"] for r in po["ladder"]}

out = []
w = out.append
w("# Quest world reference (generated by tools/survey_world_for_quests.py; do not commit)")
w("")
w("## Story ladder (master ordinal -> place, in play order)")
for r in po["ladder"]:
    w(f"  {r['ordinals']}  s{r['stage']}  {names.get('s%d' % r['stage'])}")
w("")
w("## Places. 'roam' = single-enemy roaming fights a `defeat` objective may name (species level); 'party' = other fights there")
for m in manifest["maps"]:
    sid = m["id"]
    num = sid[1:]
    scene = {}
    p = os.path.join(A, "scenes", f"{sid}.json")
    if os.path.exists(p):
        scene = load(p)
    npcs = collections.OrderedDict()
    for n in scene.get("npcs", []):
        if n.get("cutsceneOnly") or not (n.get("x") or n.get("y")) or (n.get("sprite") or "").endswith("boom"):
            continue
        npcs.setdefault(n.get("npc_id"), (n.get("sprite"), n["x"], n["y"]))
    roam, party = collections.OrderedDict(), collections.OrderedDict()
    for z in stage_enc.get(num, {}).get("zones", []):
        for s in z.get("slots", []):
            if not s:
                continue
            members = screens.get(str(s), [])
            for e in members:
                target = roam if (len(members) == 1 and z.get("rate_level", 0) > 0) else party
                lo, hi = target.get(e["name"], (e["level"], e["level"]))
                target[e["name"]] = (min(lo, e["level"]), max(hi, e["level"]))
    if not npcs and not roam and not party:
        continue
    canon = variants.get(sid, sid)
    tag = f"  [variant of {canon}]" if canon != sid else (f"  [variants: {', '.join(groups[sid])}]" if groups.get(sid) else "")
    w(f"{sid} | {m['name']}{tag}")
    if npcs:
        w("   npcs: " + ", ".join(f"{i}{'=' + persona[str(i)]['name'] if str(i) in persona else ''}:{(sp or '?')[1:]}@{x},{y}" for i, (sp, x, y) in npcs.items()))
    if roam:
        w("   roam: " + ", ".join(f"{n}({a}-{b})" if a != b else f"{n}({a})" for n, (a, b) in roam.items()))
    if party:
        w("   party: " + ", ".join(f"{n}({a}-{b})" if a != b else f"{n}({a})" for n, (a, b) in party.items()))
w("")
w("## Fight screens (a `challenge` objective names these ids)")
for sid in sorted(screens, key=lambda x: int(x)):
    members = screens[sid]
    if members:
        w(f"  {sid}: " + ", ".join(f"{e['name']}({e['level']})" for e in members))
w("")
w("## Item names a reward or `bring` objective may use")
w("  " + ", ".join(sorted(set(item_names))))

dest = os.path.join(ROOT, "docs", "generated")
os.makedirs(dest, exist_ok=True)
path = os.path.join(dest, "quests-world.txt")
open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
print(f"wrote {path} ({len(out)} lines)")
