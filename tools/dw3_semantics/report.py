"""Markdown summary of a whole-corpus pass."""

from __future__ import annotations

import json
from pathlib import Path


def _load(path: Path):
    return json.loads(path.read_text()) if path.is_file() else None


def _table(rows, headers) -> str:
    lines = ["| " + " | ".join(headers) + " |",
             "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(lines)


def build(candidates_path: Path, validation_path: Path, apply_log: Path, manifest: Path) -> str:
    candidates = _load(candidates_path)
    validation = _load(validation_path)
    applied = _load(apply_log)
    emitted = _load(manifest)

    out: list[str] = [
        "# Whole-corpus semantic inference report",
        "",
        "Generated by `tools/infer_recovered_semantics.py`. **Nothing here is "
        "verified original behavior.** Every proposed name and signature is a "
        "candidate for review; only mechanically established results were "
        "written back into `semantics.json`, and none of them at a verified "
        "status.",
        "",
    ]

    if candidates:
        summary = candidates["summary"]
        out += [
            f"Rule version `{candidates['rule_version']}`.",
            "",
            "## Corpus coverage",
            "",
            _table(
                [[key.replace("_", " "), value] for key, value in summary.items()],
                ["measure", "count"],
            ),
            "",
            "### Lift status",
            "",
            _table(sorted(candidates["lift"].items(), key=lambda i: -i[1]),
                   ["lift", "functions"]),
            "",
            "Functions reported `no_lift` have no successful decompilation. No "
            "behavior is inferred for them.",
            "",
            "### Structural roles",
            "",
            _table(sorted(candidates["roles"].items(), key=lambda i: -i[1]),
                   ["role", "functions"]),
            "",
        ]
        flags = candidates["quality_flags"]
        out += [
            "## Quality flags",
            "",
            f"- **{len(flags['rejected_phantom_entries'])}** false function "
            "boundaries were removed from the authoritative inventory before "
            "inference ran.",
            f"- **{len(flags['address_collisions'])}** addresses are claimed by "
            "more than one module; names and citations are never shared across "
            "them without module-qualified evidence.",
            f"- **{summary['weak_single_clue_names']}** proposed names rest on a "
            "single clue and are held back from automatic application.",
            f"- **{summary['with_contradictions']}** functions matched mutually "
            "incompatible roles.",
            "",
            "### Quarantine",
            "",
            _table(sorted(flags["quarantine"].items(), key=lambda i: -i[1]),
                   ["bucket", "functions"]),
            "",
        ]

    if validation:
        out += ["## Benchmarks", ""]
        if validation["leakage_detected"]:
            out.append(f"**Leakage detected in {len(validation['leakage_detected'])} "
                       "held-out ids — results below are not trustworthy.**\n")
        else:
            out.append("No leakage detected: no held-out id carried a curated name "
                       "or the curated entry-evidence marker into inference.\n")
        rows = []
        for name, scores in validation["benchmarks"].items():
            score = scores.get("accuracy")
            if score is None:
                score = scores.get("precision")
            rows.append([
                name,
                scores.get("support") or scores.get("member_pairs") or "-",
                f"{score:.1%}" if isinstance(score, float) else "-",
                f"{scores.get('recall'):.1%}" if isinstance(scores.get("recall"), float) else "-",
            ])
        out += [
            _table(rows, ["benchmark", "support", "precision/accuracy", "recall"]),
            "",
            "These are **four different capabilities**. Structural-role accuracy "
            "measures whether a body looks like a getter; semantic-name accuracy "
            "measures whether the tool arrived at the name a human gave it. High "
            "getter precision is not evidence of naming ability, and the two are "
            "never combined into a single headline number.",
            "",
        ]
        out += [
            "### Per-rule consistency",
            "",
            _table(
                [[role, counts["fired"], counts["consistent"],
                  f"{counts['consistency']:.1%}" if counts["consistency"] is not None else "-"]
                 for role, counts in validation["per_rule"].items()],
                ["rule", "fired", "consistent", "consistency"],
            ),
            "",
            f"{validation['failure_count']} benchmark failures recorded in "
            "`semantic-validation.json`.",
            "",
        ]

    if applied:
        before, after = applied["coverage_before"], applied["coverage_after"]
        out += [
            "## Application to semantics.json",
            "",
            _table(
                [[key, before[key], after[key], after[key] - before[key]]
                 for key in before],
                ["measure", "before", "after", "delta"],
            ),
            "",
            f"{applied['eligible']} candidates were eligible for automatic "
            f"application across {len(applied['batches'])} batches. "
            f"{applied['skipped_not_mechanical']} named candidates were withheld "
            "because they are heuristic rather than mechanically established.",
            "",
            "Every written entry carries `generated: true`, its rule version and "
            "its evidence paths, and the whole set is removable with "
            "`apply --revert`.",
            "",
        ]

    if emitted:
        out += [
            "## Recovered C",
            "",
            _table(sorted(emitted["grades"].items(), key=lambda i: -i[1]),
                   ["grade", "files"]),
            "",
            "`clean_typed_c` passed `gcc -fsyntax-only` on a self-contained "
            "translation unit **and** had a mechanically complete body. Every "
            "other grade is explicitly marked and is not compilable C.",
            "",
        ]

    return "\n".join(out) + "\n"
