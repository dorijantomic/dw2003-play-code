#!/usr/bin/env python3
"""Build an m2c `--context` file from signatures the lift already recovered.

m2c decompiles one function at a time.  When it meets a call it has no
declaration for, it guesses the signature from the call site alone, which is why
476 bodies carry a `?` return type, a `?` parameter or a `?` local.  Every one of
those functions, however, was itself decompiled somewhere in the corpus, and in
*its own* artifact m2c had the whole body to work from.  This tool harvests those
definition signatures and re-feeds them as context, so a caller is told what a
callee takes and returns instead of guessing.

Nothing here invents a type.  A signature is copied verbatim from the callee's
own artifact, and anything m2c could not resolve there is dropped rather than
filled in.

The one dangerous declaration is a wrong `void`: m2c applies a context signature
to the function itself, so declaring a value-returning function `void` silently
deletes every `return` and leaves a clean-looking, wrong body.  Void returns are
therefore excluded unless `--include-void` is passed, and
`tools/check_lift_regression.py` exists to prove no body lost a return.

    python3 tools/build_m2c_context.py --out exe-decomp/m2c-context.c
"""

from __future__ import annotations

import argparse
import collections
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_ROOTS = (ROOT / "exe-decomp", ROOT / "recovered/ddw3/decomp")

# m2c emits its own scalar spelling; a context file has to define it.
PRELUDE = """/* Generated by tools/build_m2c_context.py -- do not edit.
 *
 * Signatures are copied from each function's own m2c artifact, where the whole
 * body was available.  Functions whose own signature still contains `?` are
 * omitted rather than guessed.
 */
typedef signed char s8;
typedef unsigned char u8;
typedef signed short s16;
typedef unsigned short u16;
typedef signed int s32;
typedef unsigned int u32;
typedef signed long long s64;
typedef unsigned long long u64;
typedef float f32;
typedef double f64;
"""

NAME_RE = re.compile(r"F0x[0-9a-fA-F]{8}")
# The definition is the one line where the function's own name is followed by a
# parameter list and an opening brace; every other occurrence is a call or an
# `/* extern */` declaration.
RETURN_VALUE_RE = re.compile(r"(?m)^\s*return\s+\S")
# What a *caller* concluded the callee's signature is, from how it used the
# result and set up the arguments. This is the only evidence available for a
# function whose own body left m2c unable to name its return type.
EXTERN_RE = re.compile(
    r"(?m)^(?P<ret>[A-Za-z_?][\w \t*]*?)\s*\b(?P<name>F0x[0-9a-fA-F]{8})"
    r"\s*\((?P<params>[^)]*)\)\s*;\s*/\* extern \*/"
)


def definition(text: str, name: str) -> tuple[str, str] | None:
    """Return (return_type, parameters) from `name`'s definition in `text`."""
    match = re.search(
        r"(?m)^(?P<ret>[A-Za-z_?][\w \t*]*?)\s*\b" + re.escape(name)
        + r"\s*\((?P<params>[^)]*)\)\s*\{",
        text,
    )
    if match is None:
        return None
    return match.group("ret").strip(), match.group("params").strip()


def consensus(observations: collections.Counter, allow_void: bool) -> str | None:
    """The single concrete spelling every caller agreed on, else None.

    Disagreement is left unresolved rather than settled by majority: two callers
    that inferred different types are evidence that the type is not established,
    not a vote.  A `void` observation anywhere vetoes the answer unless
    explicitly allowed, because a wrong `void` return makes m2c delete returns.
    """
    seen = set(observations)
    if not seen:
        return None
    concrete = {value for value in seen if "?" not in value}
    if len(concrete) != 1:
        return None
    if not allow_void and any(value == "void" for value in seen):
        return None
    return next(iter(concrete))


def harvest(roots) -> tuple[dict[str, tuple[str, str]], collections.Counter]:
    definitions: dict[str, tuple[str, str]] = {}
    modules_of: dict[str, str] = {}
    conflicting: set[str] = set()
    caller_returns: dict[str, collections.Counter] = collections.defaultdict(
        collections.Counter
    )
    caller_params: dict[str, collections.Counter] = collections.defaultdict(
        collections.Counter
    )
    stats = collections.Counter()
    for root in roots:
        if not root.exists():
            continue
        for path in sorted(root.glob("**/F0x*.c")):
            name = path.stem
            if not NAME_RE.fullmatch(name):
                continue
            text = path.read_text(errors="replace")
            if "Decompilation failure" in text:
                stats["skipped_failed_artifact"] += 1
                continue
            module_here = (
                "exe/fns" if path.parent.name == "c"
                else f"pro/{path.parent.name.removesuffix('_c')}"
            )
            for extern in EXTERN_RE.finditer(text):
                # Keyed by module for the same reason names are: a caller in
                # `wstag640` says nothing about the different function that
                # shares that address in `wstag636`.
                callee = (module_here, extern.group("name"))
                caller_returns[callee][extern.group("ret").strip()] += 1
                caller_params[callee][extern.group("params").strip()] += 1
            found = definition(text, name)
            if found is None:
                stats["skipped_no_definition"] += 1
                continue
            # Overlays share load bases -- every `pro/wstag*` starts at
            # 0x800a5de0 -- so one `F0x` name denotes a *different* function in
            # each of them. A context is global, so a name defined in more than
            # one module must be dropped even when the two signatures happen to
            # agree: agreement between two unrelated functions is a coincidence,
            # not evidence.
            module = (
                "exe/fns" if path.parent.name == "c"
                else f"pro/{path.parent.name.removesuffix('_c')}"
            )
            if name in modules_of and modules_of[name] != module:
                conflicting.add(name)
                stats["ambiguous_across_modules"] += 1
                continue
            modules_of[name] = module
            previous = definitions.get(name)
            if previous is not None and previous != found:
                # The same function lifted twice with different signatures is an
                # unresolved disagreement, not a majority vote.
                conflicting.add(name)
                stats["conflicting"] += 1
                continue
            definitions[name] = found

    signatures: dict[str, tuple[str, str]] = {}
    for name, (ret, params) in definitions.items():
        if name in conflicting:
            continue
        key = (modules_of[name], name)
        if "?" in ret:
            # m2c could not name the return type from this body alone. The
            # callers can: each one inferred a type from how it used the result.
            resolved = consensus(caller_returns.get(key, collections.Counter()), False)
            if resolved is None:
                stats["unresolved_return"] += 1
                continue
            stats["return_from_callers"] += 1
            ret = resolved
        if "?" in params:
            resolved = consensus(caller_params.get(key, collections.Counter()), True)
            if resolved is None:
                stats["unresolved_parameter"] += 1
                continue
            stats["parameters_from_callers"] += 1
            params = resolved
        signatures[name] = (ret, params)
    return signatures, stats


def render(
    signatures: dict[str, tuple[str, str]], include_void: bool, with_params: bool
) -> tuple[str, int]:
    lines = [PRELUDE]
    emitted = 0
    for name, (ret, params) in sorted(signatures.items()):
        if not include_void and ret == "void":
            continue
        # Parameter lists are off by default. m2c infers a callee's parameters
        # from one body, and where that disagrees with what a caller actually
        # sets up, declaring the list turns a clean call into
        # `M2C_ERROR(/* Read from unset register $a0 */)` -- 10 EXE bodies went
        # from complete to `bitcast` that way. An empty list is C's "unspecified
        # parameters", so m2c keeps inferring arguments per call site while the
        # return type stays fixed, which is the part that was actually missing.
        lines.append(f"{ret} {name}({params if with_params else ''});")
        emitted += 1
    return "\n".join(lines) + "\n", emitted


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, action="append", dest="roots")
    parser.add_argument("--out", type=Path, default=ROOT / "exe-decomp/m2c-context.c")
    parser.add_argument(
        "--include-void", action="store_true",
        help="Also declare void-returning functions. Only use this together "
             "with tools/check_lift_regression.py: a wrong void deletes returns.",
    )
    parser.add_argument(
        "--with-params", action="store_true",
        help="Also declare parameter lists. Measure before keeping this: an "
             "inferred parameter list that a call site disagrees with degrades "
             "the caller.",
    )
    args = parser.parse_args()

    signatures, stats = harvest(args.roots or DEFAULT_ROOTS)
    text, emitted = render(signatures, args.include_void, args.with_params)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f"harvested={len(signatures)} emitted={emitted} out={args.out}")
    for key, value in stats.most_common():
        print(f"  {key}={value}")


if __name__ == "__main__":
    main()
