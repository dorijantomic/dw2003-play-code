_STAGE_NAMES = json.loads(
    (Path(__file__).parent / "data/stage_names.json").read_text()
)

# Per-stage music: the REAL assignment, mined from each wstag overlay's scene
# struct (+0x3c archive id -> bank; tools/extract_map_sound_archives.py,
# docs/research/audio/sound-system.md 2026-07-03d). Wilderness stages carry an
# envNNN AMBIENCE bank instead of music -- same player, env track. Replaces
# the old hand-authored name-heuristic table (which invented bgm006, a bank
# that does not exist on disc).
_SOUND_ARCHIVES = Path(__file__).parent / "web/assets/data/map_sound_archives.json"

def _load_stage_music():
    try:
        with open(_SOUND_ARCHIVES) as f:
            # A stage only PLAYS music when its scene struct carries a play id
            # (+0x40). The id's low bits select the SEQUENCE within the bank's
            # SEP (seq 0 = plain bank stem; seq N = "<bank>_N" OGG stem, e.g.
            # s212 plays env205 seq 3 -> env205_3). alt_play_ids (conditional
            # variant writers) are not auto-played.
            out = {}
            for sid, rec in json.load(f).items():
                if not rec.get("play_id") or not rec.get("bank"):
                    continue
                seq = int(rec["play_id"], 16) & 0xFFFF
                out[sid] = rec["bank"] if seq == 0 else f"{rec['bank']}_{seq}"
            return out
    except FileNotFoundError:
        print(f"WARNING: {_SOUND_ARCHIVES} missing -- run "
              "tools/extract_map_sound_archives.py first; music will be null",
              file=sys.stderr)
        return {}

_STAGE_BANK = _load_stage_music()

def _stage_music(sid):
    return _STAGE_BANK.get(sid)

def all_maps():
    maps = []
    for pack in sorted(DDW3.glob("map/dw2003/z_stage/s*pack.toml")):
        sid = pack.stem[:-4]
        maps.append({
            "id": sid,
            "name": _STAGE_NAMES.get(sid, sid),
            "music": _stage_music(sid),
        })
    for sid in bg_only_stage_ids():
        rec = {
            "id": sid,
            "name": _STAGE_NAMES.get(sid, sid),
            "music": _stage_music(sid),
            "bgSource": "bg01",
        }
        # s415's override is a controlled 320x240 runtime capture of the
        # viewport, not a world-sized tile map. Its scripted objects remain in
        # native field coordinates; FN6 projects them around the PS1 camera
        # center (160,140), while the capture itself stays screen-fixed.
        if sid == "s415":
            rec["fixedViewportBackground"] = True
            rec["cutsceneCameraCenter"] = [160, 140]
        maps.append(rec)
    # Final-ordinal s920..s974 overlays shadow 55 ordinary screen records.
    # They carry distinct stage logic but reuse the shared screen's map art.
    screen_table = json.loads(
        (Path(__file__).parent / "data/screen_table.json").read_text()
    )
    for rec in screen_table.values():
        alt = rec.get("alt")
        if not alt:
            continue
        sid = f"s{alt['stage']}"
        source = f"s{rec['stage']}"
        maps.append({
            "id": sid,
            "name": _STAGE_NAMES.get(source, source),
            "music": _stage_music(sid),
            "assetSource": source,
        })
    return maps

MAPS = all_maps()

