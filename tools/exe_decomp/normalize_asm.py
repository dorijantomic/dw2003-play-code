#!/usr/bin/env python3
"""Normalize ddw3 splat-style EXE assembly (asm/dw2003/exe/fns.s) into a form
the m2c decompiler (simonlindholm/mips_to_c) can parse.

The ddw3 disassembly uses PSY-Q/splat conventions m2c doesn't speak natively:
  - custom macros from asm/macros.s: `la_`, `move_`, `b_`, `jalr_zr`,
    `bios_call`, `bios_jump`, and the `$zr` alias for `$zero`;
  - per-instruction local labels `.L0x........:` (m2c is fine with these — they
    start with `.` so it treats them as in-function labels);
  - function starts `.global F0x........` / `F0x........:` and interleaved data
    blocks `.global D0x........` / `D0x........:` (jump tables, rodata);
  - section directives `.section "fns0_N.0xADDR"` that m2c can't map.

We rewrite each line so m2c sees plain GAS MIPS: expand the macros, alias $zr,
and put code under `.section .text` and data blocks under `.section .rodata`
(so jump tables resolve for switch recovery). %hi/%lo and `.word label` survive
untouched — m2c understands those.

Usage:
    normalize_asm.py <in.s> <out.s>
"""
import re
import sys


def _fold_reloc(m):
    """Fold integer arithmetic inside a %hi()/%lo() relocation, keeping at most
    one symbolic term. `SYM + 0x3dc*0x8 - 0x8` -> `SYM + 0x1ed0`."""
    kind, inner = m.group(1), m.group(2).strip()
    # Collect the (single) non-numeric symbol, if any.
    syms = [t for t in re.findall(r"[A-Za-z_][\w.$]*", inner)]
    expr = inner
    sym = syms[0] if syms else None
    if sym is not None:
        # Replace the symbol with 0 so the remaining arithmetic evaluates.
        expr = re.sub(r"\b" + re.escape(sym) + r"\b", "0", expr, count=1)
    try:
        off = eval(expr, {"__builtins__": {}}, {}) & 0xFFFFFFFF
    except Exception:
        return m.group(0)  # leave untouched if we can't fold
    if sym is None:
        return f"%{kind}({off:#x})"
    if off == 0:
        return f"%{kind}({sym})"
    return f"%{kind}({sym} + {off:#x})"


def expand(line: str):
    """Yield one or more normalized lines for a single input line.

    A leading `.L0x...:`/`F0x...:`/`D0x...:` label (with optional instruction)
    is split so the label stays attached to the first emitted instruction.
    """
    # Split an optional label prefix off the front.
    m = re.match(r"^(\s*(?:\.?[A-Za-z_][\w.$]*|\"[^\"]+\"):\s*)(.*)$", line)
    label, rest = (m.group(1), m.group(2)) if m else ("", line)

    rest = rest.strip()
    # $zr alias -> $zero (covers operands everywhere).
    rest = rest.replace("$zr", "$zero")
    # Constant-fold offset arithmetic inside %hi()/%lo(): m2c rejects
    # `%hi(SYM + 0x3dc * 0x8 - 0x8)`. Fold the integer terms, keep one symbol.
    rest = re.sub(r"%(hi|lo)\(([^)]*)\)", _fold_reloc, rest)

    out = []
    if not rest:
        out.append(label.rstrip())
        return out

    op = rest.split(None, 1)
    mn = op[0]
    args = op[1] if len(op) > 1 else ""

    def emit(s):
        out.append((label if not out else "") + s)

    if mn == "la_":
        reg, addr = [a.strip() for a in args.split(",", 1)]
        emit(f"lui {reg}, %hi({addr})")
        emit(f"addiu {reg}, {reg}, %lo({addr})")
    elif mn == "move_":
        lhs, rhs = [a.strip() for a in args.split(",", 1)]
        emit(f"move {lhs}, {rhs}")
    elif mn == "b_":
        emit(f"b {args.strip()}")
    elif mn == "jalr_zr":
        emit("jalr $zero, $zero")
    elif mn == "bios_call":
        family, idx = [a.strip() for a in args.split(",", 1)]
        emit(f"li $t1, {idx}")
        emit(f"li $t2, {family}")
        emit("jalr $t2")
        emit("nop")
    elif mn == "bios_jump":
        family, idx = [a.strip() for a in args.split(",", 1)]
        emit(f"li $t2, {family}")
        emit("jr $t2")
        emit(f"li $t1, {idx}")
        emit("nop")
    else:
        emit(rest)
    return out


def normalize(src_lines):
    out = ["# auto-generated by tools/exe_decomp/normalize_asm.py", ".set noat"]
    section = None  # current logical section we've emitted
    for raw in src_lines:
        line = raw.rstrip("\n")
        stripped = line.strip()
        if not stripped:
            continue
        # Drop directives m2c can't use / we handle ourselves.
        if stripped.startswith(".include"):
            continue
        if stripped.startswith(".set") and ("$zr" in stripped or "noreorder" in stripped or "noat" in stripped):
            continue
        # Section directive: decide text vs rodata from its name suffix is
        # unreliable, so we switch sections based on the *labels* we encounter
        # instead (below). Drop the raw `.section "..."` line.
        if stripped.startswith(".section"):
            continue
        # A `.global D0x...` introduces a data block -> rodata; `.global F0x...`
        # (or a bare F-label) introduces code -> text.
        gm = re.match(r"^\.global\s+(\w+)", stripped)
        if gm:
            name = gm.group(1)
            want = ".rodata" if name.startswith("D0x") else ".text"
            if section != want:
                out.append(want)
                section = want
            out.append(f".global {name}")
            continue
        # Bare label lines also signal section (e.g. D0x...: with no .global).
        lm = re.match(r"^(D0x[0-9a-fA-F]+|F0x[0-9a-fA-F]+):", stripped)
        if lm:
            want = ".rodata" if lm.group(1).startswith("D0x") else ".text"
            if section != want:
                out.append(want)
                section = want
        for e in expand(line):
            if e.strip():
                # Fold offset arithmetic in any %hi()/%lo() (incl. la_-expanded).
                out.append(re.sub(r"%(hi|lo)\(([^)]*)\)", _fold_reloc, e))
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(1)
    src = open(sys.argv[1]).read().splitlines()
    open(sys.argv[2], "w").write(normalize(src))
    print(f"wrote {sys.argv[2]}")


if __name__ == "__main__":
    main()
