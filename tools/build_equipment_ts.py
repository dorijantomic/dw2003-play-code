#!/usr/bin/env python3
"""Generate engine/dw3/equipment-data.ts from web/assets/data/equipment.json.

The EQUIPMENT catalog used to be a hand-pasted array inside engine/dw3/equipment.ts;
that copy carried build_equipment.py's off-by-one (fixed 2026-07-10) and predated the
accessory-effect decode. equipment.ts keeps the helpers (equipItem/equipmentBonuses/...)
and imports the catalog from here.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "web/assets/data/equipment.json"
OUT = ROOT / "engine/dw3/equipment-data.ts"


def main() -> None:
    rows = json.loads(SRC.read_text())["equipment"]
    lines = [
        "// engine/dw3/equipment-data.ts — GENERATED by tools/build_equipment_ts.py; do not edit.",
        "// Source: web/assets/data/equipment.json (tools/build_equipment.py — Unknown0/1/2 tables).",
        "// Accessory `effect` decode: docs/research/battle/accessory-effects-decoded-2026-07-10.md.",
        "",
        "export interface AccessoryEffect {",
        '  kind: string;            // "stat" | "elem_resist" | "status_resist" | opcode name',
        "  amount: number;",
        "  stat?: string;           // kind=stat: str/def/spt/wis/spd/chr",
        "  element?: string;        // kind=elem_resist / elem_attack",
        "  status?: string;         // kind=status_resist: poison/paralyze/confuse/sleep/ko",
        "}",
        "",
        "export interface EquipmentItem {",
        "  id: number;",
        "  name: string;",
        '  slot: "head" | "body" | "right" | "left" | "accessory";',
        "  buyPrice: number;",
        "  sellPrice: number;",
        "  family: number;          // Unknown1 byte +0x9: which stat-record branch applies",
        "  statBytes?: number[];    // raw equip-stat record (20 B Unknown0 / 12 B Unknown2)",
        "  accPool?: number;        // stat-record byte +0x0E -> combatant +0x3a to-hit pool",
        "  evadePool?: number;      // stat-record byte +0x10 -> combatant +0x3b to-evade pool",
        "  wearMask: number;        // 8-bit starter-line gear-access mask (stat-record byte +4)",
        "  effect?: AccessoryEffect;",
        "}",
        "",
        "export const EQUIPMENT: EquipmentItem[] = [",
    ]
    for r in rows:
        parts = [
            f"id: {r['id']}", f"name: {json.dumps(r['name'])}",
            f"slot: {json.dumps(r['slot'])}",
            f"buyPrice: {r['buy_price']}", f"sellPrice: {r['sell_price']}",
            f"family: {r['family']}", f"wearMask: {r['wear_mask']}",
        ]
        if "stat_bytes" in r:
            parts.append("statBytes: [" + ", ".join(str(b) for b in r["stat_bytes"]) + "]")
        if "acc_pool" in r:
            parts.append(f"accPool: {r['acc_pool']}")
        if "evade_pool" in r:
            parts.append(f"evadePool: {r['evade_pool']}")
        eff = r.get("effect")
        if eff:
            e = [f"kind: {json.dumps(eff['kind'])}", f"amount: {eff.get('amount', 0)}"]
            for k in ("stat", "element", "status"):
                if k in eff:
                    e.append(f"{k}: {json.dumps(eff[k])}")
            parts.append("effect: { " + ", ".join(e) + " }")
        lines.append("  { " + ", ".join(parts) + " },")
    lines += ["];", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {len(rows)} entries -> {OUT}")


if __name__ == "__main__":
    main()
