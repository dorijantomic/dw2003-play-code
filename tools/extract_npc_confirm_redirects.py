#!/usr/bin/env python3
"""Extract the confirm press's id-REDIRECT pair table (fieldstg F0x8008E2CC).

When the field confirm press (talk/examine) resolves its target, the interact
handler F0x8008E2CC (pro/fieldstg.s file 0xb61c-0xb7a8, overlay base
0x80082CB0) first tests the target's npc_id against a flat pair list at RAM
0x80097C68 (fieldstg.s file 0xb674-0xb6b0):

    .L0x0000b674: lh   $v0, 0x7c68($a1)     # first pair's id (0 = no table)
    .L0x0000b694: lh   $v0, ($v1)           # pair id
    .L0x0000b69c: beq  $a0, $v0, .L0x0000b720
    .L0x0000b6a4: lh   $v0, 0x4($v1)        # next pair's id ends the walk
    ...
    .L0x0000b720: li   $a0, 5
    .L0x0000b724: lh   $a1, 0x2($a1)        # the redirect id (pair+2)
    .L0x0000b728: lw   $v0, -0x4844($v0)    # [0x8004b7bc] = find_entity
    .L0x0000b730: jalr $v0                  # find_entity(5, redirect_id, -1)

So an npc_id in the table is replaced by the class-5 entity carrying the
redirect id before the interact arms run (and before the block-actor id range
test).  The fifteen ids are exactly the spriteless position markers the walker
had been FILTERING out of the talk pool (112/113 at the s210/211/220/221/923/924
counters, and friends); the redirect is what makes the press reach the clerk
behind them.

Writes engine/dw3/npc-confirm-redirects.ts. Run from the repository root:

    DW3_DISC=/path/to/dw2003.bin .venv/bin/python3 tools/extract_npc_confirm_redirects.py

(Overlay parsing: run under the repo's usual cap, e.g.
`taskset -c 0 prlimit --as=4294967296 -- ...`.)
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

TABLE_BASE = 0x80097C68      # pair list {u16 id, u16 redirect_id}
LOAD_BASE = 0x80082CB0       # FIELDSTG.PRO overlay load base
FIELDSTG_IDX = 358           # LBA file index of FIELDSTG.PRO
MAX_PAIRS = 64               # the walk ends on a zero id; bounds the read


def read_pairs(image: bytes) -> list[tuple[int, int]]:
    off = TABLE_BASE - LOAD_BASE
    pairs: list[tuple[int, int]] = []
    for i in range(MAX_PAIRS):
        a, b = struct.unpack_from("<HH", image, off + i * 4)
        if a == 0:
            break
        pairs.append((a, b))
    return pairs


def main() -> int:
    from extract_point_sprites import Disc, DISC  # existing disc reader

    image = Disc(DISC).file(FIELDSTG_IDX)
    pairs = read_pairs(image)
    if not pairs:
        raise SystemExit("the redirect table read as empty; wrong offset or image")
    if any(a == b for a, b in pairs):
        raise SystemExit(f"a redirect maps an id to itself: {pairs}")
    if len(pairs) == MAX_PAIRS:
        raise SystemExit("no zero-id terminator inside the bound; wrong table?")

    # Cross-check against the shipped overlay image when it is present: the walker
    # tests read web/assets/native/fieldstg.bin, and the two must agree byte-for-byte.
    shipped = ROOT / "web/assets/native/fieldstg.bin"
    if shipped.exists():
        if read_pairs(shipped.read_bytes()) != pairs:
            raise SystemExit("shipped fieldstg.bin disagrees with the disc image")

    out: list[str] = [
        "// Generated by tools/extract_npc_confirm_redirects.py — the confirm press's",
        "// id-REDIRECT pair table at RAM 0x80097C68 (FIELDSTG.PRO, overlay base",
        "// 0x80082CB0), read by the interact handler F0x8008E2CC (pro/fieldstg.s file",
        "// 0xb674-0xb73c): an npc_id found here is replaced by the class-5 entity with",
        "// the redirect id before the interact arms run. The ids are the spriteless",
        "// position markers at counters and checkpoints; the redirect is what makes a",
        "// press at the marker reach the character behind it. Ledger claim",
        "// field-confirm-engage-dispatcher.",
        "",
        "export const NPC_CONFIRM_REDIRECT_TABLE_RAM = 0x80097c68;",
        "",
        "const CONFIRM_REDIRECT_PAIRS: readonly (readonly [number, number])[] = [",
    ]
    for a, b in pairs:
        out.append(f"  [{a}, {b}],")
    out += [
        "];",
        "",
        "/** Every pair, in table order. */",
        "export function confirmRedirectPairs(): readonly (readonly [number, number])[] {",
        "  return CONFIRM_REDIRECT_PAIRS;",
        "}",
        "",
        "/** The id the confirm press retargets to, or null when the id is not in the",
        " *  table (the disc then keeps the probed target). */",
        "export function confirmRedirectId(npcId: number | null | undefined): number | null {",
        "  if (npcId == null || !Number.isFinite(npcId)) return null;",
        "  for (const [id, to] of CONFIRM_REDIRECT_PAIRS) if (id === npcId) return to;",
        "  return null;",
        "}",
        "",
    ]
    (ROOT / "engine/dw3/npc-confirm-redirects.ts").write_text("\n".join(out))
    print(f"wrote engine/dw3/npc-confirm-redirects.ts ({len(pairs)} pairs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
