#!/usr/bin/env python3
"""Emit the effect-interpreter's performance table as TypeScript.

An opcode is a PERFORMANCE when its handlers put something on screen and the
disc's interpreter holds the frame until it finishes. Which opcodes those are,
and which share handlers, is read from `cardgame-opcode-registry.json` (both
phases for all 174 at authority 2). The human-readable family name comes from
`docs/research/ui/symbols/cardgame.json`.

Derived, not hand-written, so it cannot drift from the registry. Regenerate with:
    .venv/bin/python3 tools/gen_card_performance_table.py
"""
import json, collections

R = '/home/dorij/ddw3-walker/'
reg = json.load(open(R + 'docs/research/card/cardgame-opcode-registry.json'))['opcodes']
syms = {int(f['address'], 16): f.get('name', '?')
        for f in json.load(open(R + 'docs/research/ui/symbols/cardgame.json'))['functions']}


def row(o):
    return reg.get('0x%02X' % o) or reg.get('0x%02x' % o)


def callee(d):
    cs = d.get('callees') or []
    return cs[0] if cs else None


def name(c):
    return syms.get(int(c.replace('F0x', ''), 16), '?') if c else None


fam = collections.OrderedDict()
for o in range(1, 0xAF):
    r = row(o)
    if not r:
        continue
    key = (callee(r['enter']), callee(r['update']))
    fam.setdefault(key, []).append(o)

lines = [
    '// GENERATED by tools/gen_card_performance_table.py — do not edit by hand.',
    '//',
    '// Every opcode that reaches a handler pair, and the family name of that',
    '// pair. Derived from docs/research/card/cardgame-opcode-registry.json',
    '// (both phases for all 174 opcodes, authority 2) joined to the names in',
    '// docs/research/ui/symbols/cardgame.json.',
    '//',
    '// This says WHICH opcodes share handlers. It does NOT say they behave',
    '// alike — the handlers take arguments, and one family of nineteen differs',
    '// only in a mask whose board bits are still an open question.',
    'export const OPCODE_FAMILY: Readonly<Record<number, string>> = Object.freeze({',
]
for key, ops in fam.items():
    fname = name(key[1]) or name(key[0])
    if not fname or fname == '?':
        continue
    for o in ops:
        lines.append('  0x%02x: %s,' % (o, json.dumps(fname)))
lines.append('});')
out = R + 'engine/systems/card-opcode-families.ts'
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote %s — %d families, %d opcodes' % (out, len(fam), sum(len(v) for v in fam.values())))
