#!/usr/bin/env python3
"""Street-vehicle tables: the per-stage path starts and sprite ids the field
cars use.

Both tables live in the stage overlay and are read by the overlay's own code,
so they are extracted from the overlay words rather than hand-written:

  * sprite id byte table at RAM 0x800A83C0 (file 0x25e0). The car tick
    materialises it at wstag780.s file 0x1e4-0x1e8
    (`lui $v0,0x800b` / `addiu $a1,-0x7c40` = 0x800a83c0) and indexes it with
    `(ctr>>2) + obj[+0x50]*2 + obj[+0x5c]*4`.
  * 8-byte `{x, y}` start-position records at RAM 0x800A83C8 (file 0x25e8),
    materialised by the spawner at file 0x2bc-0x2c0
    (`lui $v0,0x800b` / `addiu $v0,-0x7c38` = 0x800a83c8) and indexed with
    `a0*32 + a1*16 + a2*8`.

Usage:
  python3 tools/extract_street_vehicle_tables.py --check   # compare (default)
  python3 tools/extract_street_vehicle_tables.py --write   # regenerate
"""

from __future__ import annotations

import re
import struct
import sys
from pathlib import Path

ASM = Path.home() / "ddw3/asm/dw2003/pro"
OVERLAY_BASE = 0x800A5DE0
OUT = Path(__file__).resolve().parent.parent / "engine/dw3/street-vehicle-tables.ts"

STAGES = {"s780": "wstag780.s"}
SPRITE_TABLE_RAM = 0x800A83C0
SPRITE_TABLE_LEN = 8
PATH_TABLE_RAM = 0x800A83C8
PATH_RECORDS = 8

WORD_RE = re.compile(
    r"\.L0x([0-9a-f]{8}): (?:\.word 0x([0-9a-f]+)|.*?# \.word 0x([0-9a-f]+))"
)


def load_words(path: Path) -> dict[int, int]:
    words: dict[int, int] = {}
    for m in WORD_RE.finditer(path.read_text()):
        words[int(m.group(1), 16)] = int(m.group(2) or m.group(3), 16)
    if not words:
        raise SystemExit(f"{path}: no overlay words found")
    return words


def tables(path: Path) -> tuple[list[int], list[tuple[int, int]]]:
    words = load_words(path)
    img = bytearray(max(words) + 4)
    for off, w in words.items():
        struct.pack_into("<I", img, off, w)
    s_off = SPRITE_TABLE_RAM - OVERLAY_BASE
    sprites = list(img[s_off : s_off + SPRITE_TABLE_LEN])
    p_off = PATH_TABLE_RAM - OVERLAY_BASE
    paths = [
        struct.unpack_from("<2I", img, p_off + i * 8) for i in range(PATH_RECORDS)
    ]
    return sprites, paths


def render(sprites: list[int], paths: list[tuple[int, int]]) -> str:
    sp = ", ".join(str(v) for v in sprites)
    pa = ",\n".join(f"            [{x}, {y}]" for x, y in paths)
    return (
        "// GENERATED by tools/extract_street_vehicle_tables.py — do not hand-edit.\n"
        "//\n"
        "// Per-stage tables for the field street vehicles (engine/systems/\n"
        "// street-vehicles.ts). Decode:\n"
        "// docs/research/field/asuka-city-cars-and-news-screens-2026-10-04.md\n"
        "\n"
        "export interface StreetVehicleTables {\n"
        "    /** 8-byte {x, y} start records; index = a0 * 32 + a1 * 16 + a2 * 8. */\n"
        "    paths: readonly (readonly [number, number])[];\n"
        "    /** sprite-id bytes; index = (ctr >> 2) + dirY * 2 + variant * 4. */\n"
        "    sprites: readonly number[];\n"
        "}\n"
        "\n"
        f"export const STREET_VEHICLE_TABLES: Record<string, StreetVehicleTables> = {{\n"
        f"    s780: {{\n"
        f"        sprites: [{sp}],\n"
        f"        paths: [\n{pa},\n"
        f"        ],\n"
        f"    }},\n"
        f"}};\n"
    )


def main() -> None:
    got: dict[str, tuple[list[int], list[tuple[int, int]]]] = {}
    for stage, fname in STAGES.items():
        got[stage] = tables(ASM / fname)
    text = render(got["s780"][0], got["s780"][1])
    if "--write" in sys.argv:
        OUT.write_text(text)
        print(f"wrote {OUT}")
        return
    if not OUT.exists():
        raise SystemExit(f"{OUT} missing; run with --write")
    cur = OUT.read_text()
    if cur != text:
        raise SystemExit(
            f"{OUT} differs from the disc tables; rerun with --write\n"
            f"  disc: {got['s780']}"
        )
    print(f"{OUT} matches the disc tables: {got['s780']}")


if __name__ == "__main__":
    main()